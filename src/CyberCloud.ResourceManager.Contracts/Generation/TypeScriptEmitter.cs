    static string Head() =>
        Banner + "\n"
        + "// Generated from the published OpenAPI document — docs/plan/21 § Generation's one hop.\n"
        + "// ./build.sh Generate overwrites this file and ./build.sh Architecture fails on a\n"
        + "// difference. docs/plan/03 § Assembly graph rules, rule 6.\n";

    /// <summary>The interface name a scope's create body takes.</summary>
    static string ScopeInterface(DocumentScope scope) => Pascal(scope.Kind) + "CreateContent";

    /// <summary>The union name one enum leaf takes.</summary>
    /// <summary>
    ///     The model name a resource type takes — its display name, or its type path.
    /// </summary>
    /// <remarks>
    ///     ⚠ <b>Not <c>SdkEmitter</c>'s, and the difference is deliberate.</b> That emitter resolves
    ///     collisions by prefixing the provider, because two providers will both have a
    ///     <c>servers</c>. This one keys on the fully qualified type path instead, which is unique by
    ///     construction — the registry keys on it — so there is no collision to resolve and no
    ///     second-pass rule that could disagree with the first.
    /// </remarks>
    static string ModelOf(DocumentType type) =>
        Pascal(type.ProviderNamespace.Split('.')[^1]) + Pascal(type.TypePath);

    static string Member(string name) =>
        name.Length > 0 && (char.IsAsciiLetter(name[0]) || name[0] is '_' or '$')
        && name.All(x => char.IsAsciiLetterOrDigit(x) || x is '_' or '$')
            ? name
            : Quote(name);

    /// <summary>A TypeScript single-quoted string literal.</summary>
    static string Quote(string value) =>
        "'" + value.Replace("\\", "\\\\", StringComparison.Ordinal)
            .Replace("'", "\\'", StringComparison.Ordinal)
            .Replace("\r\n", " ", StringComparison.Ordinal)
            .Replace("\n", " ", StringComparison.Ordinal) + "'";

    /// <summary>
    ///     Text that is safe inside a <c>/** … */</c> comment, on one line.
    /// </summary>
    /// <remarks>
    ///     ⚠ <c>*/</c> in a description would end the comment and turn the rest of the sentence into
    ///     a syntax error, exactly as a newline does in <c>SdkEmitter.Escape</c>'s <c>///</c>.
    /// </remarks>
    static string Comment(string value) =>
        value.Replace("*/", "* /", StringComparison.Ordinal)
            .Replace("\r\n", " ", StringComparison.Ordinal)
            .Replace("\n", " ", StringComparison.Ordinal);

    /// <summary>Any identifier-ish string as <c>PascalCase</c>, invariantly.</summary>
    /// <remarks>⚠ <see cref="SdkEmitter.Pascal" />'s, so the two surfaces name a type the same way.</remarks>
    static string Pascal(string value) => SdkEmitter.Pascal(value);

    /// <summary>Any identifier-ish string as <c>camelCase</c>, invariantly.</summary>
    static string Camel(string value) {
        var pascal = Pascal(value);

        return char.ToLowerInvariant(pascal[0]) + pascal[1..];
    }
