        + "\tMethod string\n"
        + "\tPath   string\n"
        + "\tQuery  url.Values\n"
        + "\t// Marshalled as JSON when non-nil.\n"
        + "\tBody any\n"
        + "}\n"
        + "\n"
        + "// Response is what came back. ⚠ A scope PUT answers 201 the first time and 200 on a repeat.\n"
        + "type Response struct {\n"
        + "\tStatusCode int\n"
        + "\tHeader     http.Header\n"
        + "\tBody       []byte\n"
        + "}\n"
        + "\n"
        + "// RetryAfter reads Retry-After as a delay. Only the delta-seconds form; a date reads as absent.\n"
        + "func (r *Response) RetryAfter() (time.Duration, bool) {\n"
        + "\tseconds, err := strconv.ParseFloat(r.Header.Get(\"Retry-After\"), 64)\n"
        + "\tif err != nil {\n"
        + "\t\treturn 0, false\n"
        + "\t}\n"
        + "\treturn time.Duration(seconds * float64(time.Second)), true\n"
        + "}\n"
        + "\n"
        + "// Transport is how the client reaches the platform. HTTPTransport is the net/http one; a test\n"
        + "// supplies a fake. ⚠ Send never fails on a 4xx or 5xx: the client turns those into the one error\n"
        + "// shape. It fails when no response arrived at all.\n"
        + "type Transport interface {\n"
