using System.Collections.Immutable;
using System.Text;
using System.Text.Json.Nodes;

namespace CyberCloud.ResourceManager.Contracts.Generation;

/// <summary>
///     The Go SDK: ADR-012's surfaces, in the language the Terraform provider needs — issue #40.
/// </summary>
/// <remarks>
///     <para>
///         ⚠ <b>Reads the published OpenAPI document, not the registry</b>, for the reason on
///         <see cref="PythonSdkEmitter" /> and <see cref="TypeScriptEmitter" />: docs/plan/21
///         § Generation's one hop puts every client under the compatibility diff over that
///         document, and an emitter that read the registry would be outside it.
///     </para>
///     <para>
///         <b>What is emitted, per api-version</b> — a package <c>api{version}</c> in its own
///         directory: <c>models.go</c> with one struct per schema and one string type per closed
///         set, <c>client.go</c> with one client per resource type grouped under its provider,
///         and <c>runtime.go</c> with the transport seam, a <c>net/http</c> transport, the one
///         error shape, the operation poller, and the <c>$skipToken</c> pager. One <c>go.mod</c>
///         at the root, so <c>go vet ./...</c> over <c>generated/sdk-go</c> compiles every
///         api-version at once.
///     </para>
///     <para>
///         ⚠
///         <b>
///             A container is its own named struct, which is Go's spelling of the #79
///             convention.
///         </b> Go has no nested types, and an anonymous struct type has to be
///         repeated at every place a caller constructs one, so <c>/properties/persistence</c> is
///         <c>{Model}PropertiesPersistence</c>: a name per container, each leaf carrying its own
///         wire name in its <c>json</c> tag at its own depth. The read shape holds the envelope
///         embedded and the body as <c>Data</c>, and reads the same bytes twice — the shape the
///         .NET hand-written half arrived at for the same problem (#85).
///     </para>
///     <para>
///         ⚠ <b>The package directory is <c>api20260801</c>, not <c>v20260801</c>.</b> A path
///         element of the form <c>vN</c> is a major-version suffix to the Go module system, and a
///         directory that looks like one is a directory whose imports resolve differently from
///         the way they read.
///     </para>
///     <para>
///         ⚠ <b>What this cannot check, said plainly.</b> Nothing in the .NET build runs Go.
///         <see cref="Problems" /> is the cheap self-check, and the
///         <c>
/// Generated Go SDK
///         compiles
///         </c> gate in <c>build/Build.Architecture.cs</c> runs <c>go vet</c> over the
///         checked-in module when <c>go</c> is on <c>PATH</c>, reporting ○ with the reason when
///         it is not rather than ✔.
///     </para>
/// </remarks>
public static class GoSdkEmitter {
    /// <summary>The subdirectory of <c>generated/</c> the module is checked in at.</summary>
    public const string DirectoryName = "sdk-go";

    /// <summary>The module path — where the module is checked in, which is the one truthful path.</summary>
    public const string ModulePath = "github.com/Rikarin/CyberCloud/generated/sdk-go";

    /// <summary>
    ///     The Go release the module declares. ⚠ Generics and <c>any</c> need 1.18; <c>slices</c> would need 1.21 and is
    ///     not used.
    /// </summary>
    public const string GoVersion = "1.22";

    /// <summary>
    ///     The banner every emitted file carries in its first line — Go's own convention, which tools such as
    ///     <c>golint</c> honour.
    /// </summary>
    const string Banner =
        "// Code generated by CyberCloud.ResourceManager.Contracts.Generation.GoSdkEmitter. DO NOT EDIT.";

    /// <summary>The package one api-version's client lives in — <c>api20260801</c>.</summary>
    /// <param name="apiVersion">The api-version, as the document spells it.</param>
    public static string PackageOf(string apiVersion) {
        ArgumentNullException.ThrowIfNull(apiVersion);

        return "api" + apiVersion.Replace("-", string.Empty, StringComparison.Ordinal);
    }

    /// <summary>The files every run writes once — the module file.</summary>
    /// <returns>The files, keyed by their path under <c>generated/sdk-go</c>.</returns>
    public static ImmutableSortedDictionary<string, string> Root() =>
        ImmutableSortedDictionary.CreateRange(
            StringComparer.Ordinal,
            new Dictionary<string, string>(StringComparer.Ordinal) {
                ["go.mod"] = Banner
                    + "\n// @generated — ./build.sh Generate overwrites this file and ./build.sh Architecture fails on a difference.\n"
                    + "\n"
                    + "module "
                    + ModulePath
                    + "\n"
                    + "\n"
                    + "go "
                    + GoVersion
                    + "\n"
            }
        );

    /// <summary>Emits one api-version's package, keyed by path under <c>generated/sdk-go</c>.</summary>
    /// <param name="document">An emitted OpenAPI document.</param>
    public static ImmutableSortedDictionary<string, string> Emit(JsonObject document) {
        ArgumentNullException.ThrowIfNull(document);

        var version = DocumentReader.VersionOf(document);
        var types = DocumentReader.TypesOf(document);
        var scopes = DocumentReader.ScopesOf(document);
        var objects = DocumentReader.ScopeObjectsOf(document);
        var names = SdkEmitter.ModelNames(types);
        var package = PackageOf(version);
        var directory = package + "/";

        return ImmutableSortedDictionary.CreateRange(
            StringComparer.Ordinal,
            new Dictionary<string, string>(StringComparer.Ordinal) {
                [directory + "models.go"] = Models(version, package, document, types, scopes, objects, names),
                [directory + "client.go"] = Client(version, package, document, types, scopes, objects, names),
                [directory + "runtime.go"] = Runtime(version, package)
            }
        );
    }

    // ── models.go ──────────────────────────────────────────────────────────────────────────────

    static string Models(
        string version,
        string package,
        JsonObject document,
        ImmutableArray<DocumentType> types,
        ImmutableArray<DocumentScope> scopes,
        ImmutableArray<DocumentScopeObject> objects,
        ImmutableDictionary<string, string> names
    ) {
        var built = new StringBuilder(Head(version));

        built.Append("\n// Package ")
            .Append(package)
            .Append(" is the CyberCloud API at api-version ")
            .Append(version)
            .Append(", typed.\n")
            .Append("//\n// One client per resource type under its provider, one struct per schema nested exactly as\n")
            .Append("// the wire is, Begin* for every long-running verb, and a pager for every collection.\n")
            .Append("package ")
            .Append(package)
            .Append("\n\n")
            .Append("import \"encoding/json\"\n");

        var declared = new Declared();

        AppendErrorModels(built, document, declared);
        AppendOperationModels(built, document, declared);
        AppendScopeModels(built, document, scopes, declared);
        AppendScopeObjectModels(built, objects, declared);
        AppendEnvelope(built, document, declared);

        foreach (var type in types) {
            AppendTypeModels(built, type, names[type.ResourceType], declared);
        }

        // ⚠ encoding/json is imported unconditionally and used by every MarshalJSON and
        // UnmarshalJSON; a document with no resource type would leave it unused, which Go refuses,
        // so a reference is kept alive for that document alone.
        built.Append("\nvar _ = json.Marshal\n");

        return built.ToString();
    }

    /// <summary>The type names one file declares, refused when one is declared twice.</summary>
    sealed class Declared {
        readonly Dictionary<string, string> names = new(StringComparer.Ordinal);

        public void Claim(string name, string origin) {
            if (names.TryGetValue(name, out var other)) {
                throw new InvalidOperationException(
                    $"'{origin}' and '{other}' both generate the Go type '{name}'. Two declarations of one "
                    + "name do not compile, and the error would surface in a consumer's build rather than here."
                );
            }

            names[name] = origin;
        }
    }

    static void AppendErrorModels(StringBuilder built, JsonObject document, Declared declared) {
        var codes = DocumentReader.EnumOf(document["components"]?["schemas"]?["ErrorCode"] as JsonObject ?? []);

        AppendEnum(
            built,
            "ErrorCode",
            "a stable, documented, greppable identifier. ⚠ Part of the API contract.",
            codes,
            "ErrorCode",
            declared
        );

        declared.Claim("Error", "the error shape");

        built.Append("\n// Error is the one error shape — docs/plan/08 § Errors.\n")
            .Append("type Error struct {\n")
            .Append("\tCode    ErrorCode `json:\"code\"`\n")
            .Append("\tMessage string    `json:\"message\"`\n")
            .Append("\t// An RFC 6901 JSON Pointer into the request body, so a form can highlight the field.\n")
            .Append("\tTarget *string `json:\"target,omitempty\"`\n")
            .Append(
                "\t// Every other problem found. A form that has to be fixed one field per round trip is a form nobody finishes.\n"
            )
            .Append("\tDetails []Error `json:\"details,omitempty\"`\n")
            .Append("}\n\n")
            .Append("// Error renders the code and the message, which is what a log line wants.\n")
            .Append("func (e *Error) Error() string {\n")
            .Append("\treturn string(e.Code) + \": \" + e.Message\n")
            .Append("}\n");
    }

    static void AppendOperationModels(StringBuilder built, JsonObject document, Declared declared) {
        var schemas = document["components"]?["schemas"] as JsonObject;

        if (schemas?[OpenApiEmitter.OperationStatusSchema] is not JsonObject status) {
            return;
        }

        var states = DocumentReader.EnumOf(schemas[OpenApiEmitter.OperationStateSchema] as JsonObject ?? []);

        AppendEnum(
            built,
            "OperationState",
            "Azure's status vocabulary. ⚠ Terminal means Succeeded, Failed or Canceled; poll until then.",
            states,
            "OperationState",
            declared
        );

        if (schemas[OpenApiEmitter.OperationProgressSchema] is JsonObject progress) {
            var leaves = DocumentReader.LeavesOf(progress);

            AppendStruct(
                built,
                "OperationProgress",
                DocumentReader.Text(progress["description"]),
                leaves.Where(static x => !x.IsObject)
                    .Select(static x => Field(x, default, "OperationProgress", true))
                    .ToList(),
                declared,
                "OperationProgress"
            );
        }

        // ⚠ The three $ref members written out, as the TypeScript and Python emitters do: LeavesOf
        // reads a $ref as untyped. Present or a pointer as x-cybercloud-read-required says.
        var served = DocumentReader.ReadRequiredOf(status);
        var fields = new List<GoField>();

        foreach (var leaf in DocumentReader.LeavesOf(status)) {
            switch (leaf.Name) {
                case "error":
                    fields.Add(
                        new(
                            "Error",
                            "*Error",
                            "error,omitempty",
                            "Present once the status is Failed, and the reason.",
                            false
                        )
                    );
                    break;

                case "progress":
                    fields.Add(
                        new(
                            "Progress",
                            "[]OperationProgress",
                            served.Contains(leaf.Name) ? "progress" : "progress,omitempty",
                            "Oldest first. What makes a nine-minute cluster creation tolerable — docs/plan/10.",
                            false
                        )
                    );
                    break;

                case "status":
                    fields.Add(new("Status", "OperationState", "status", string.Empty, false));
                    break;

                default:
                    fields.Add(
                        Field(
                            leaf with { Required = leaf.Required || served.Contains(leaf.Name) },
                            default,
                            "OperationStatus",
                            true
                        )
                    );
                    break;
            }
        }

        AppendStruct(
            built,
            "OperationStatus",
            DocumentReader.Text(status["description"]),
            fields,
            declared,
            "OperationStatus"
        );
    }

    static void AppendScopeModels(
        StringBuilder built,
        JsonObject document,
        ImmutableArray<DocumentScope> scopes,
        Declared declared
    ) {
        if (scopes.IsEmpty) {
            return;
        }

        var schema = document["components"]?["schemas"]?[OpenApiEmitter.ScopeSchema] as JsonObject ?? [];
        var leaves = DocumentReader.LeavesOf(schema);
        var naming = EnumNaming.For("Scope", leaves);

        AppendEnums(built, naming, leaves, declared);
        AppendStruct(
            built,
            "ScopeResource",
            "a tenant, a subscription or a resource group, as the API renders it. ⚠ There is no provisioningState: a scope converges before the call returns.",
            leaves.Where(static x => !x.IsObject).Select(x => Field(x, naming, "ScopeResource", true)).ToList(),
            declared,
            "ScopeResource"
        );

        foreach (var scope in scopes.Where(static x => x.Creatable)) {
            var name = ScopeContent(scope);

            AppendObjectStruct(
                built,
                name,
                "the body of a PUT that creates a " + scope.DisplayName.ToLowerInvariant() + ".",
                scope.Body,
                string.Empty,
                EnumNaming.For(name, DocumentReader.LeavesOf(scope.Body)),
                declared,
                name
            );
        }
    }

    /// <summary>
    ///     The objects addressed on a scope — issue #46's policy — one read struct and one write
    ///     struct per object, whatever the number of scopes it sits on.
    /// </summary>
    static void AppendScopeObjectModels(StringBuilder built, ImmutableArray<DocumentScopeObject> objects, Declared declared) {
        var emitted = new HashSet<string>(StringComparer.Ordinal);

        foreach (var scoped in objects) {
            if (emitted.Add(scoped.ModelName)) {
                AppendScopeObjectModel(
                    built,
                    scoped.ModelName,
                    scoped.Resource,
                    "a " + Comment(scoped.DisplayName.ToLowerInvariant()) + ", as the API renders it. " + scoped.Summary,
                    declared,
                    scoped.Component
                );
            }

            if (scoped.ContentName.Length > 0 && emitted.Add(scoped.ContentName)) {
                AppendScopeObjectModel(
                    built,
                    scoped.ContentName,
                    scoped.Content,
                    "the body of a PUT that writes a " + scoped.DisplayName.ToLowerInvariant() + ".",
                    declared,
                    scoped.ContentComponent
                );
            }
        }
    }

    static void AppendScopeObjectModel(
        StringBuilder built,
        string name,
        JsonObject schema,
        string doc,
        Declared declared,
        string origin
    ) {
        var leaves = DocumentReader.LeavesOf(schema);
        var naming = EnumNaming.For(name, leaves);

        AppendEnums(built, naming, leaves, declared);
        AppendObjectStruct(built, name, doc, schema, string.Empty, naming, declared, origin);
    }

    /// <summary>
    ///     <c>ProvisioningState</c> and <c>Resource</c> once for the file, from the document's own
    ///     component — the read envelope every type embeds (#85).
    /// </summary>
    static void AppendEnvelope(StringBuilder built, JsonObject document, Declared declared) {
        if (document["components"]?["schemas"]?[OpenApiEmitter.ResourceEnvelopeSchema] is not JsonObject envelope) {
            return;
        }

        var served = DocumentReader.ReadRequiredOf(envelope);
        var leaves = DocumentReader.LeavesOf(envelope);
        var naming = EnumNaming.For(string.Empty, leaves);

        AppendEnums(built, naming, leaves, declared);
        AppendStruct(
            built,
            "Resource",
            DocumentReader.Text(envelope["description"]),
            leaves.Where(static x => !x.IsObject)
                .Select(x => Field(x with { Required = served.Contains(x.Name) }, naming, "Resource", true))
                .ToList(),
            declared,
            "Resource"
        );
    }

    static void AppendTypeModels(StringBuilder built, DocumentType type, string model, Declared declared) {
        var leaves = DocumentReader.LeavesOf(type.Body);
        var naming = EnumNaming.For(model, leaves);

        AppendEnums(built, naming, leaves, declared);
        AppendObjectStruct(
            built,
            model + "Data",
            type.DisplayName + ": the body a caller writes." + Summary(type),
            type.Body,
            string.Empty,
            naming,
            declared,
            model
        );

        // ⚠ THE READ SHAPE IS THE ENVELOPE PLUS THE WRITE BODY — issue #85 — and the same bytes are
        // read twice. Embedding both structs would promote a MarshalJSON from either onto this one,
        // which is a Go trap with no warning: json.Marshal of the resource would silently render
        // the body alone. Holding Data as a named field keeps the two apart.
        var hasEnvelope = !DocumentReader.LeavesOf(type.Envelope).IsEmpty;

        declared.Claim(model + "Resource", type.ResourceType);

        built.Append("\n// ")
            .Append(model)
            .Append("Resource is one ")
            .Append(Comment(type.DisplayName))
            .Append(", as the API returns it: the Resource envelope, then the body. ⚠ Read, never written.\n")
            .Append("type ")
            .Append(model)
            .Append("Resource struct {\n");

        if (hasEnvelope) {
            built.Append("\tResource\n");
        }

        built.Append("\t// The body, as the caller wrote it and the manager holds it.\n")
            .Append("\tData ")
            .Append(model)
            .Append("Data\n")
            .Append("}\n\n")
            .Append("// UnmarshalJSON reads the envelope and the body off one object.\n")
            .Append("func (r *")
            .Append(model)
            .Append("Resource) UnmarshalJSON(data []byte) error {\n");

        if (hasEnvelope) {
            built.Append("\tif err := json.Unmarshal(data, &r.Resource); err != nil {\n\t\treturn err\n\t}\n");
        }

        built.Append("\treturn json.Unmarshal(data, &r.Data)\n")
            .Append("}\n");

        foreach (var action in type.Actions) {
            if (action.Request is { } request) {
                var name = model + SdkEmitter.Pascal(action.Name) + "Content";
                var requestLeaves = DocumentReader.LeavesOf(request);
                var requestNaming = EnumNaming.For(name, requestLeaves);

                AppendEnums(built, requestNaming, requestLeaves, declared);
                AppendObjectStruct(
                    built,
                    name,
                    "the parameters of " + action.Name + ".",
                    request,
                    string.Empty,
                    requestNaming,
                    declared,
                    type.ResourceType + "/" + action.Name
                );
            }

            if (action.Response is { } response) {
                var name = model + SdkEmitter.Pascal(action.Name) + "Result";
                var responseLeaves = DocumentReader.LeavesOf(response);
                var responseNaming = EnumNaming.For(name, responseLeaves);

                AppendEnums(built, responseNaming, responseLeaves, declared);
                AppendObjectStruct(
                    built,
                    name,
                    "what "
                    + action.Name
                    + " returns."
                    + (action.Secret ? " ⚠ Secret material — never log or persist this." : string.Empty),
                    response,
                    string.Empty,
                    responseNaming,
                    declared,
                    type.ResourceType + "/" + action.Name
                );
            }
        }
    }

    /// <summary>One string type per closed set, before the struct that names them.</summary>
    static void AppendEnums(
        StringBuilder built,
        EnumNaming naming,
        ImmutableArray<SchemaLeaf> leaves,
        Declared declared
    ) {
        foreach (var leaf in leaves) {
            var values = DocumentReader.EnumOf(leaf.Schema);

            if (leaf.IsObject || values.IsEmpty) {
                continue;
            }

            AppendEnum(
                built,
                naming.NameOf(leaf),
                "the values "
                + leaf.JsonPointer
                + (DocumentReader.Flag(leaf.Schema["readOnly"])
                        ? " carries. ⚠ Read-only: the server sets it, and a write that carries it is refused."
                        : " accepts. ⚠ Closed: the write path refuses anything else."),
                values,
                leaf.JsonPointer,
                declared
            );
        }
    }

    /// <summary>
    ///     A string type and a constant per value.
    /// </summary>
    /// <remarks>
    ///     ⚠ A string type rather than an <c>int</c> with <c>iota</c>: a value a newer server
    ///     adds to a read-only vocabulary still parses, and a caller can compare against the
    ///     literal. The constant names are <c>{Type}{Value}</c> Pascal-cased, so two values that
    ///     differ only in punctuation — <c>aof</c> and <c>AOF</c> — are one identifier and are
    ///     refused here rather than left as a duplicate declaration.
    /// </remarks>
    static void AppendEnum(
        StringBuilder built,
        string name,
        string doc,
        ImmutableArray<string> values,
        string origin,
        Declared declared
    ) {
        declared.Claim(name, origin);

        built.Append("\n// ")
            .Append(name)
            .Append(" is ")
            .Append(Comment(doc))
            .Append('\n')
            .Append("type ")
            .Append(name)
            .Append(" string\n");

        if (values.IsEmpty) {
            return;
        }

        var taken = new Dictionary<string, string>(StringComparer.Ordinal);
        var constants = new List<(string Constant, string Value)>();

        foreach (var value in values) {
            var constant = name + SdkEmitter.Pascal(value);

            if (taken.TryGetValue(constant, out var other)) {
                throw new InvalidOperationException(
                    $"'{origin}' declares the values '{value}' and '{other}', which are both the Go constant "
                    + $"'{constant}'. Two constants with one name do not compile."
                );
            }

            taken[constant] = value;
            constants.Add((constant, value));
        }

        var width = constants.Max(static x => x.Constant.Length);

        built.Append("\nconst (\n");

        foreach (var (constant, value) in constants) {
            built.Append('\t')
                .Append(constant.PadRight(width))
                .Append(' ')
                .Append(name)
                .Append(" = ")
                .Append(Quote(value))
                .Append('\n');
        }

        built.Append(")\n");
    }

    /// <summary>One struct field.</summary>
    /// <param name="Name">The exported identifier.</param>
    /// <param name="Type">The Go type, pointer and all.</param>
    /// <param name="Tag">The <c>json</c> tag's value.</param>
    /// <param name="Doc">A comment above the field, or empty.</param>
    /// <param name="ReadOnly">Whether <c>MarshalJSON</c> clears it before a write.</param>
    readonly record struct GoField(string Name, string Type, string Tag, string Doc, bool ReadOnly);

    /// <summary>A scalar leaf as a field.</summary>
    /// <param name="leaf">The leaf.</param>
    /// <param name="naming">How the owner's closed sets are named.</param>
    /// <param name="owner">The struct the field is on.</param>
    /// <param name="read">
    ///     Whether the struct is only ever read — the envelope, a scope, an operation. ⚠ Every
    ///     member of the read envelope is <c>readOnly</c> in the document, and on a struct nothing
    ///     writes that is not a reason for a pointer: <c>resource.ID</c> is a <c>string</c>, not a
    ///     <c>*string</c> a caller has to nil-check for a value a read always carries.
    /// </param>
    static GoField Field(SchemaLeaf leaf, EnumNaming naming, string owner, bool read = false) {
        var schema = leaf.Schema;
        var values = DocumentReader.EnumOf(schema);
        var nullable = DocumentReader.IsNullable(schema);
        var readOnly = !read && DocumentReader.Flag(schema["readOnly"]);
        var kind = DocumentReader.TypeOf(schema);

        var bare = !values.IsEmpty && naming.Model is not null && kind != "array"
            ? naming.NameOf(leaf)
            : kind switch {
                "array" => "[]" + Scalar(schema["items"] as JsonObject ?? [], naming, leaf),
                // ⚠ Any JSON value — a policy rule — held as the bytes the wire carried, before the
                // object branch reads it as the tag bag's map.
                "object" when DocumentReader.IsJsonValue(schema) => "json.RawMessage",
                "object" => "map[string]string",
                var scalar => Scalar(schema, naming, leaf, scalar)
            };

        // ⚠ A pointer whenever "absent" and "zero" must stay apart: an optional bool that is
        // false, an optional count that is zero, a nullable string that is null. A required
        // scalar is a value, so a caller cannot construct a body the API refuses by leaving it
        // out — a read-only leaf is a pointer whatever the schema says, so MarshalJSON can clear
        // it. A slice and a map are already nil-able and never take a pointer.
        var reference = kind is "array" or "object";
        var pointer = !reference && (!leaf.Required || nullable || readOnly);
        var omit = !leaf.Required || readOnly;
        var tag = leaf.Name + (omit ? ",omitempty" : string.Empty);

        return new(
            GoName(leaf.Name),
            (pointer ? "*" : string.Empty) + bare,
            tag,
            DocumentReader.Text(schema["description"]),
            readOnly
        );
    }

    static string Scalar(JsonObject schema, EnumNaming naming, SchemaLeaf leaf, string? declared = null) {
        if (!DocumentReader.EnumOf(schema).IsEmpty
            && naming.Model is not null
            && DocumentReader.TypeOf(leaf.Schema) == "array") {
            return naming.NameOf(leaf);
        }

        return (declared ?? DocumentReader.TypeOf(schema)) switch {
            "integer" => "int64",
            "number" => "float64",
            "boolean" => "bool",
            "string" => "string",
            _ => "any"
        };
    }

    /// <summary>
    ///     One object schema as a struct, its containers as further named structs after it.
    ///     <c>origin</c> is what a collision message names.
    /// </summary>
    static void AppendObjectStruct(
        StringBuilder built,
        string name,
        string doc,
        JsonObject schema,
        string pointer,
        EnumNaming naming,
        Declared declared,
        string origin
    ) {
        var fields = new List<GoField>();
        var nested = new List<(string Name, SchemaLeaf Leaf)>();
        var taken = new Dictionary<string, string>(StringComparer.Ordinal);

        if (schema["properties"] is JsonObject properties) {
            var required = schema["required"] is JsonArray names
                ? names.Select(DocumentReader.Text).ToHashSet(StringComparer.Ordinal)
                : [];

            foreach (var member in properties.ToList().OrderBy(static x => x.Key, StringComparer.Ordinal)) {
                if (member.Value is not JsonObject child) {
                    continue;
                }

                var isObject = DocumentReader.TypeOf(child) == "object" && child["properties"] is JsonObject;
                var leaf = new SchemaLeaf(
                    pointer + "/" + member.Key,
                    member.Key,
                    child,
                    required.Contains(member.Key),
                    isObject
                );
                var identifier = GoName(member.Key);

                if (taken.TryGetValue(identifier, out var other)) {
                    throw new InvalidOperationException(
                        $"'{leaf.JsonPointer}' and '{other}' would both be the field '{identifier}' on {name}. Two "
                        + "fields with one name do not compile."
                    );
                }

                taken[identifier] = leaf.JsonPointer;

                if (!isObject) {
                    fields.Add(Field(leaf, naming, name));
                    continue;
                }

                var childName = name.EndsWith("Data", StringComparison.Ordinal) && pointer.Length == 0
                    ? name[..^4] + SdkEmitter.Pascal(member.Key)
                    : name + SdkEmitter.Pascal(member.Key);

                nested.Add((childName, leaf));

                fields.Add(
                    new(
                        identifier,
                        (leaf.Required ? string.Empty : "*") + childName,
                        member.Key + (leaf.Required ? string.Empty : ",omitempty"),
                        DocumentReader.Text(child["description"]),
                        false
                    )
                );
            }
        }

        AppendStruct(built, name, doc, fields, declared, origin);

        foreach (var (childName, leaf) in nested) {
            AppendObjectStruct(
                built,
                childName,
                DocumentReader.Text(leaf.Schema["description"]) is { Length: > 0 } text
                    ? text
                    : "the " + leaf.Name + " object of " + name + ".",
                leaf.Schema,
                leaf.JsonPointer,
                naming,
                declared,
                origin + " " + leaf.JsonPointer
            );
        }
    }

    static void AppendStruct(
        StringBuilder built,
        string name,
        string doc,
        List<GoField> fields,
        Declared declared,
        string origin
    ) {
        declared.Claim(name, origin);

        built.Append("\n// ")
            .Append(name)
            .Append(" is ")
            .Append(Comment(doc))
            .Append('\n')
            .Append("type ")
            .Append(name)
            .Append(" struct {\n");

        if (fields.Count == 0) {
            built.Append("\t// The document declares no member.\n");
        }

        // ⚠ Aligned the way gofmt aligns a struct — name, type and tag in columns over each run of
        // fields, a comment line ending the run — so the checked-in file is what gofmt would
        // write and a reader's editor does not reformat a generated file on open.
        foreach (var run in Runs(fields)) {
            var names = run.Max(static x => x.Name.Length);
            var types = run.Max(static x => x.Type.Length);

            foreach (var field in run) {
                if (field.Doc.Length > 0) {
                    built.Append("\t// ").Append(Comment(field.Doc)).Append('\n');
                }

                built.Append('\t')
                    .Append(field.Name.PadRight(names))
                    .Append(' ')
                    .Append(field.Type.PadRight(types))
                    .Append(" `json:\"")
                    .Append(field.Tag)
                    .Append("\"`\n");
            }
        }

        built.Append("}\n");

        var readOnly = fields.Where(static x => x.ReadOnly).ToList();

        if (readOnly.Count == 0) {
            return;
        }

        // ⚠ A read-only member is read and never written: the write path refuses one rather than
        // ignoring it (docs/plan/08 § The write path, end to end), so a body read off a GET and
        // sent back on a PUT would be refused for a member the caller never set. The alias type
        // strips this method so the call does not recurse.
        built.Append("\n// MarshalJSON writes the struct with its read-only members cleared: ")
            .Append(string.Join(", ", readOnly.Select(static x => x.Name)))
            .Append(". The write path refuses a read-only member rather than ignoring it.\n")
            .Append("func (v ")
            .Append(name)
            .Append(") MarshalJSON() ([]byte, error) {\n")
            .Append("\ttype plain ")
            .Append(name)
            .Append('\n')
            .Append("\tstripped := plain(v)\n");

        foreach (var field in readOnly) {
            built.Append("\tstripped.").Append(field.Name).Append(" = nil\n");
        }

        built.Append("\treturn json.Marshal(stripped)\n")
            .Append("}\n");
    }

    /// <summary>
    ///     The fields of one struct split into the runs gofmt aligns separately — a field with a
    ///     comment above it starts a new run, because the comment line has no columns.
    /// </summary>
    static List<List<GoField>> Runs(List<GoField> fields) {
        var runs = new List<List<GoField>>();

        foreach (var field in fields) {
            if (runs.Count == 0 || field.Doc.Length > 0) {
                runs.Add([]);
            }

            runs[^1].Add(field);
        }

        return runs;
    }

    /// <summary>
    ///     How one model's string types are named — the same rule the other clients apply, for
    ///     the same colliding pair.
    /// </summary>
    readonly record struct EnumNaming(string Model, ImmutableHashSet<string> Ambiguous) {
        public static EnumNaming For(string model, ImmutableArray<SchemaLeaf> leaves) {
            var counts = new Dictionary<string, int>(StringComparer.Ordinal);

            foreach (var leaf in leaves) {
                if (leaf.IsObject || DocumentReader.EnumOf(leaf.Schema).IsEmpty) {
                    continue;
                }

                counts[leaf.Name] = counts.GetValueOrDefault(leaf.Name) + 1;
            }

            return new(model, [.. counts.Where(static x => x.Value > 1).Select(static x => x.Key)]);
        }

        public string NameOf(SchemaLeaf leaf) =>
            Model + (Ambiguous.Contains(leaf.Name) ? NestedName(leaf.JsonPointer) : SdkEmitter.Pascal(leaf.Name));
    }

    static string NestedName(string jsonPointer) {
        var segments = jsonPointer.Split('/', StringSplitOptions.RemoveEmptyEntries);

        if (segments.Length > 1 && string.Equals(segments[0], "properties", StringComparison.Ordinal)) {
            segments = segments[1..];
        }

        return string.Concat(segments.Select(SdkEmitter.Pascal));
    }

    // ── client.go ──────────────────────────────────────────────────────────────────────────────

    static string Client(
        string version,
        string package,
        JsonObject document,
        ImmutableArray<DocumentType> types,
        ImmutableArray<DocumentScope> scopes,
        ImmutableArray<DocumentScopeObject> objects,
        ImmutableDictionary<string, string> names
    ) {
        var built = new StringBuilder(Head(version));
        var polls = document["paths"]?[OperationPath] is JsonObject;

        built.Append("\npackage ")
            .Append(package)
            .Append("\n\n")
            .Append("import (\n\t\"context\"\n\t\"net/url\"\n)\n\n")
            .Append(
                "// GeneratedAPIVersion is the api-version this client was generated at. The transport sends it on every request.\n"
            )
            .Append("const GeneratedAPIVersion = ")
            .Append(Quote(version))
            .Append("\n\n")
            .Append(
                "// segment percent-encodes one path segment. ⚠ A name is caller data and a '/' in one would forge a path.\n"
            )
            .Append("func segment(value string) string {\n\treturn url.PathEscape(value)\n}\n");

        var groups = types.GroupBy(static x => x.ProviderNamespace, StringComparer.Ordinal)
            .OrderBy(static x => x.Key, StringComparer.Ordinal)
            .ToList();

        var families = objects.GroupBy(static x => x.Group, StringComparer.Ordinal)
            .OrderBy(static x => x.Key, StringComparer.Ordinal)
            .ToList();

        AppendRootClient(built, version, polls, scopes, families.Select(static x => x.Key).ToList(), groups);

        if (polls) {
            AppendOperationsClient(built);
        }

        foreach (var scope in scopes) {
            AppendScopeClient(built, scope);
        }

        foreach (var family in families) {
            AppendScopeObjectClient(built, family.Key, family.ToList());
        }

        foreach (var group in groups) {
            AppendProviderGroup(built, group.Key, group.ToList(), names);

            foreach (var type in group) {
                AppendTypeClient(built, type, names[type.ResourceType]);
            }
        }

        // ⚠ context is used by every method; a document with no path at all would leave it unused,
        // which Go refuses, so a reference is kept alive for that document alone.
        built.Append("\nvar _ = context.Canceled\n");

        return built.ToString();
    }

    const string OperationPath = "/operations/{operationId}";

    static void AppendRootClient(
        StringBuilder built,
        string version,
        bool polls,
        ImmutableArray<DocumentScope> scopes,
        List<string> families,
        List<IGrouping<string, DocumentType>> groups
    ) {
        built.Append("\n// Client is the public REST API at api-version ")
            .Append(version)
            .Append(".\n")
            .Append(
                "//\n// ⚠ Every method builds a path and hands it to the transport. Authentication, the api-version\n"
            )
            .Append("// query parameter and correlation are the transport's; HTTPTransport is the net/http one, and\n")
            .Append("// anything implementing Transport can replace it.\n");

        var members = new List<(string Field, string Type, string Value)>();

        if (polls) {
            members.Add(("Operations", "*OperationsClient", "&OperationsClient{transport: transport}"));
        }

        foreach (var scope in scopes) {
            members.Add(
                (ScopeClientField(scope), "*" + ScopeClientField(scope) + "Client",
                    "&" + ScopeClientField(scope) + "Client{transport: transport}")
            );
        }

        foreach (var family in families) {
            var field = SdkEmitter.Pascal(family);
            members.Add((field, "*" + field + "Client", "&" + field + "Client{transport: transport}"));
        }

        foreach (var group in groups) {
            var segment = SdkEmitter.Pascal(group.Key.Split('.')[^1]);

            if (segment is "Operations" or "Tenants" or "Subscriptions" or "ResourceGroups" or "ManagementGroups"
                || families.Contains(segment, StringComparer.Ordinal)) {
                throw new InvalidOperationException(
                    $"The provider namespace '{group.Key}' would be the field '{segment}' on Client, which the "
                    + "client already declares for the platform's own API."
                );
            }

            members.Add((segment, "*" + segment + "Provider", "new" + segment + "Provider(transport)"));
        }

        AppendHolder(built, "Client", "NewClient", "builds a client over one transport.", members);
    }

    /// <summary>
    ///     A struct of clients and the function that builds it, aligned the way gofmt aligns a
    ///     field list and a keyed composite literal.
    /// </summary>
    static void AppendHolder(
        StringBuilder built,
        string name,
        string constructor,
        string doc,
        List<(string Field, string Type, string Value)> members
    ) {
        var width = members.Count == 0 ? 0 : members.Max(static x => x.Field.Length);

        built.Append("type ").Append(name).Append(" struct {\n");

        foreach (var (field, type, _) in members) {
            built.Append('\t').Append(field.PadRight(width)).Append(' ').Append(type).Append('\n');
        }

        built.Append("}\n\n")
            .Append("// ")
            .Append(constructor)
            .Append(' ')
            .Append(doc)
            .Append('\n')
            .Append("func ")
            .Append(constructor)
            .Append("(transport Transport) *")
            .Append(name)
            .Append(" {\n")
            .Append("\treturn &")
            .Append(name)
            .Append("{\n");

        foreach (var (field, _, value) in members) {
            built.Append("\t\t").Append((field + ":").PadRight(width + 1)).Append(' ').Append(value).Append(",\n");
        }

        built.Append("\t}\n}\n");
    }

