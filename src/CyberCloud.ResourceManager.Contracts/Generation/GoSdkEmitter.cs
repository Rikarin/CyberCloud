        + "}\n"
        + "\n"
        + "// TokenProvider returns a bearer token. Asked on every request, so a caller that caches and\n"
        + "// refreshes owns that policy.\n"
        + "type TokenProvider func(ctx context.Context) (string, error)\n"
        + "\n"
        + "// HTTPTransport is net/http, a bearer token, and nothing else — no retry, no keychain. docs/plan/21\n"
        + "// § The .NET SDK's credential types are the hand-written half this module does not have yet.\n"
        + "type HTTPTransport struct {\n"
        + "\tEndpoint string\n"
        + "\tToken    TokenProvider\n"
        + "\t// nil means http.DefaultClient.\n"
        + "\tClient *http.Client\n"
        + "}\n"
        + "\n"
        + "// Send makes one request.\n"
        + "func (t *HTTPTransport) Send(ctx context.Context, request *Request) (*Response, error) {\n"
        + "\tquery := url.Values{}\n"
        + "\tfor name, values := range request.Query {\n"
        + "\t\tquery[name] = values\n"
        + "\t}\n"
        + "\tquery.Set(\"api-version\", APIVersion)\n"
        + "\ttarget := strings.TrimRight(t.Endpoint, \"/\") + request.Path + \"?\" + query.Encode()\n"
        + "\tvar body io.Reader\n"
        + "\tif request.Body != nil {\n"
        + "\t\tencoded, err := json.Marshal(request.Body)\n"
        + "\t\tif err != nil {\n"
        + "\t\t\treturn nil, err\n"
        + "\t\t}\n"
        + "\t\tbody = bytes.NewReader(encoded)\n"
        + "\t}\n"
        + "\thttpRequest, err := http.NewRequestWithContext(ctx, request.Method, target, body)\n"
        + "\tif err != nil {\n"
        + "\t\treturn nil, err\n"
        + "\t}\n"
        + "\ttoken, err := t.Token(ctx)\n"
        + "\tif err != nil {\n"
        + "\t\treturn nil, err\n"
        + "\t}\n"
        + "\thttpRequest.Header.Set(\"Authorization\", \"Bearer \"+token)\n"
        + "\thttpRequest.Header.Set(\"Accept\", \"application/json\")\n"
        + "\t// docs/plan/10 § Request pipeline: one correlation id per logical request.\n"
        + "\thttpRequest.Header.Set(\"x-ms-correlation-request-id\", correlationID())\n"
        + "\tif body != nil {\n"
        + "\t\thttpRequest.Header.Set(\"Content-Type\", \"application/json; charset=utf-8\")\n"
        + "\t}\n"
        + "\tclient := t.Client\n"
        + "\tif client == nil {\n"
        + "\t\tclient = http.DefaultClient\n"
        + "\t}\n"
        + "\thttpResponse, err := client.Do(httpRequest)\n"
        + "\tif err != nil {\n"
        + "\t\treturn nil, err\n"
        + "\t}\n"
        + "\tdefer httpResponse.Body.Close()\n"
        + "\tcontent, err := io.ReadAll(httpResponse.Body)\n"
        + "\tif err != nil {\n"
        + "\t\treturn nil, err\n"
        + "\t}\n"
        + "\treturn &Response{StatusCode: httpResponse.StatusCode, Header: httpResponse.Header, Body: content}, nil\n"
        + "}\n"
        + "\n"
        + "func correlationID() string {\n"
        + "\tvar random [16]byte\n"
        + "\tif _, err := rand.Read(random[:]); err != nil {\n"
        + "\t\treturn \"\"\n"
        + "\t}\n"
        + "\treturn fmt.Sprintf(\"%x-%x-%x-%x-%x\", random[0:4], random[4:6], random[6:8], random[8:10], random[10:16])\n"
        + "}\n"
        + "\n"
        + "// RequestFailedError is a 4xx or 5xx, carrying the one error shape when the body had it —\n"
        + "// docs/plan/08 § Errors. ⚠ Also returned when a poll reports a Failed or Canceled operation: the\n"
        + "// poll itself was a 200, and the error is the operation's.\n"
        + "type RequestFailedError struct {\n"
        + "\tStatusCode int\n"
        + "\t// nil when the body did not carry the shape.\n"
        + "\tErr *Error\n"
        + "}\n"
        + "\n"
        + "// Error renders the status and, when there is one, the code and the message.\n"
        + "func (e *RequestFailedError) Error() string {\n"
        + "\tif e.Err == nil {\n"
        + "\t\treturn \"HTTP \" + strconv.Itoa(e.StatusCode)\n"
        + "\t}\n"
        + "\treturn e.Err.Error()\n"
        + "}\n"
        + "\n"
        + "// Unwrap exposes the error shape to errors.As.\n"
        + "func (e *RequestFailedError) Unwrap() error {\n"
        + "\tif e.Err == nil {\n"
        + "\t\treturn nil\n"
        + "\t}\n"
        + "\treturn e.Err\n"
        + "}\n"
        + "\n"
        + "// Code is the error code, or \"\" when the body did not carry one.\n"
        + "func (e *RequestFailedError) Code() ErrorCode {\n"
        + "\tif e.Err == nil {\n"
        + "\t\treturn \"\"\n"
        + "\t}\n"
        + "\treturn e.Err.Code\n"
        + "}\n"
        + "\n"
        + "// ParseError reads the error shape off a failed response, or nil when the body does not carry it.\n"
        + "func ParseError(response *Response) *Error {\n"
        + "\tvar envelope struct {\n"
        + "\t\tError *Error `json:\"error\"`\n"
        + "\t}\n"
        + "\tif err := json.Unmarshal(response.Body, &envelope); err != nil || envelope.Error == nil || envelope.Error.Code == \"\" {\n"
        + "\t\treturn nil\n"
        + "\t}\n"
        + "\treturn envelope.Error\n"
        + "}\n"
        + "\n"
        + "// checkStatus is the one place a response becomes an error.\n"
        + "func checkStatus(response *Response) error {\n"
        + "\tif response.StatusCode < 400 {\n"
        + "\t\treturn nil\n"
        + "\t}\n"
        + "\treturn &RequestFailedError{StatusCode: response.StatusCode, Err: ParseError(response)}\n"
        + "}\n"
        + "\n"
        + "// call sends one request, refuses a 4xx or 5xx, and decodes the body into result when one is wanted.\n"
        + "func call(ctx context.Context, transport Transport, method string, path string, body any, result any) error {\n"
        + "\tresponse, err := transport.Send(ctx, &Request{Method: method, Path: path, Body: body})\n"
        + "\tif err != nil {\n"
        + "\t\treturn err\n"
        + "\t}\n"
        + "\tif err := checkStatus(response); err != nil {\n"
        + "\t\treturn err\n"
        + "\t}\n"
        + "\tif result == nil {\n"
        + "\t\treturn nil\n"
        + "\t}\n"
        + "\treturn decode(response, result)\n"
        + "}\n"
        + "\n"
        + "func decode(response *Response, into any) error {\n"
        + "\tif err := json.Unmarshal(response.Body, into); err != nil {\n"
        + "\t\treturn fmt.Errorf(\"the response body is not the shape the document declares: %w\", err)\n"
        + "\t}\n"
        + "\treturn nil\n"
        + "}\n"
        + "\n"
        + "// relative is a GET of an absolute URL's path and query. ⚠ The origin is dropped: a bearer token\n"
        + "// follows the endpoint, never a URL the response chose. The query is parsed into members so the\n"
        + "// transport's own api-version replaces the one the link carried rather than following it.\n"
        + "func relative(raw string) (*Request, error) {\n"
        + "\tparsed, err := url.Parse(raw)\n"
        + "\tif err != nil {\n"
        + "\t\treturn nil, err\n"
        + "\t}\n"
        + "\treturn &Request{Method: \"GET\", Path: parsed.EscapedPath(), Query: parsed.Query()}, nil\n"
        + "}\n"
        + "\n"
        + "// Operation is a long-running operation — docs/plan/10 § Long-running operations, over HTTP. Built\n"
        + "// from the 202: Poll reads the status once; Wait polls until the status is terminal and then reads\n"
        + "// the resource, or returns a RequestFailedError with the operation's error.\n"
        + "//\n"
        + "// ⚠ No goroutine and no timer of its own: every poll is driven by the caller, so nothing keeps\n"
        + "// polling after the caller has walked away.\n"
        + "type Operation[T any] struct {\n"
        + "\t// Interval overrides the server's Retry-After between polls when set. ⚠ The server's number wins\n"
        + "\t// by default: it is back-pressure, and a client that polls a nine-minute operation every 100 ms\n"
        + "\t// spends its rate-limit budget finding out nothing changed.\n"
        + "\tInterval time.Duration\n"
        + "\n"
        + "\ttransport    Transport\n"
        + "\tid           string\n"
        + "\tresourcePath string\n"
        + "\tretryAfter   time.Duration\n"
        + "\tstatus       *OperationStatus\n"
        + "\treported     int\n"
        + "}\n"
        + "\n"
        + "// begin sends a write and wraps its 202. resourcePath is what Wait reads on success, or \"\" for a delete.\n"
        + "func begin[T any](ctx context.Context, transport Transport, method string, path string, body any, resourcePath string) (*Operation[T], error) {\n"
        + "\tresponse, err := transport.Send(ctx, &Request{Method: method, Path: path, Body: body})\n"
        + "\tif err != nil {\n"
        + "\t\treturn nil, err\n"
        + "\t}\n"
        + "\tif err := checkStatus(response); err != nil {\n"
        + "\t\treturn nil, err\n"
        + "\t}\n"
        + "\treturn newOperation[T](transport, response, resourcePath)\n"
        + "}\n"
        + "\n"
        + "func newOperation[T any](transport Transport, accepted *Response, resourcePath string) (*Operation[T], error) {\n"
        + "\tlocation := accepted.Header.Get(\"Azure-AsyncOperation\")\n"
        + "\tif location == \"\" {\n"
        + "\t\treturn nil, &RequestFailedError{StatusCode: accepted.StatusCode, Err: &Error{Code: \"InternalError\", Message: \"The 202 carried no Azure-AsyncOperation header, so the operation cannot be polled.\"}}\n"
        + "\t}\n"
        + "\tparsed, err := url.Parse(location)\n"
        + "\tif err != nil {\n"
        + "\t\treturn nil, err\n"
        + "\t}\n"
        + "\t// ⚠ The last segment as the id, never the URL itself: the poll goes to the transport's endpoint.\n"
        + "\tpath := strings.TrimRight(parsed.Path, \"/\")\n"
        + "\tid := path[strings.LastIndex(path, \"/\")+1:]\n"
        + "\tretryAfter, _ := accepted.RetryAfter()\n"
        + "\treturn &Operation[T]{transport: transport, id: id, resourcePath: resourcePath, retryAfter: retryAfter}, nil\n"
        + "}\n"
        + "\n"
        + "// ID is the operation id — the last segment of the Azure-AsyncOperation URL.\n"
        + "func (o *Operation[T]) ID() string {\n"
        + "\treturn o.id\n"
        + "}\n"
        + "\n"
        + "// Status is the last polled status, or nil before the first poll.\n"
        + "func (o *Operation[T]) Status() *OperationStatus {\n"
        + "\treturn o.status\n"
        + "}\n"
        + "\n"
        + "// Done reports whether the last poll saw a terminal status.\n"
        + "func (o *Operation[T]) Done() bool {\n"
        + "\treturn o.status != nil && (o.status.Status == \"Succeeded\" || o.status.Status == \"Failed\" || o.status.Status == \"Canceled\")\n"
        + "}\n"
        + "\n"
        + "// Poll reads the status once. ⚠ A poll that fails is not an operation that fails: a 429 is returned as itself.\n"
        + "func (o *Operation[T]) Poll(ctx context.Context) (*OperationStatus, error) {\n"
        + "\tresponse, err := o.transport.Send(ctx, &Request{Method: \"GET\", Path: \"/operations/\" + url.PathEscape(o.id)})\n"
        + "\tif err != nil {\n"
        + "\t\treturn nil, err\n"
        + "\t}\n"
        + "\tif err := checkStatus(response); err != nil {\n"
        + "\t\treturn nil, err\n"
        + "\t}\n"
        + "\tvar status OperationStatus\n"
        + "\tif err := decode(response, &status); err != nil {\n"
        + "\t\treturn nil, err\n"
        + "\t}\n"
        + "\to.status = &status\n"
        + "\to.retryAfter, _ = response.RetryAfter()\n"
        + "\treturn &status, nil\n"
        + "}\n"
        + "\n"
        + "// Wait polls until the status is terminal, reporting each new progress entry to onProgress when it\n"
        + "// is not nil, then reads the resource. A delete resolves to an empty value.\n"
        + "func (o *Operation[T]) Wait(ctx context.Context, onProgress func(OperationProgress)) (*T, error) {\n"
        + "\tfor !o.Done() {\n"
        + "\t\tdelay := o.Interval\n"
        + "\t\tif delay == 0 {\n"
        + "\t\t\tdelay = o.retryAfter\n"
        + "\t\t}\n"
        + "\t\tif delay == 0 {\n"
        + "\t\t\tdelay = time.Second\n"
        + "\t\t}\n"
        + "\t\tselect {\n"
        + "\t\tcase <-ctx.Done():\n"
        + "\t\t\treturn nil, ctx.Err()\n"
        + "\t\tcase <-time.After(delay):\n"
        + "\t\t}\n"
        + "\t\tstatus, err := o.Poll(ctx)\n"
        + "\t\tif err != nil {\n"
        + "\t\t\treturn nil, err\n"
        + "\t\t}\n"
        + "\t\tif onProgress != nil {\n"
        + "\t\t\tfor _, entry := range status.Progress[min(o.reported, len(status.Progress)):] {\n"
        + "\t\t\t\tonProgress(entry)\n"
        + "\t\t\t}\n"
        + "\t\t}\n"
        + "\t\tif len(status.Progress) > o.reported {\n"
        + "\t\t\to.reported = len(status.Progress)\n"
        + "\t\t}\n"
        + "\t}\n"
        + "\tif o.status.Status != \"Succeeded\" {\n"
        + "\t\tfailure := o.status.Error\n"
        + "\t\tif failure == nil {\n"
        + "\t\t\tcode := ErrorCode(\"ProvisioningFailed\")\n"
        + "\t\t\tif o.status.Status == \"Canceled\" {\n"
        + "\t\t\t\tcode = \"OperationCanceled\"\n"
        + "\t\t\t}\n"
        + "\t\t\tfailure = &Error{Code: code, Message: \"The operation ended in state \" + string(o.status.Status) + \" without an error body.\"}\n"
        + "\t\t}\n"
        + "\t\treturn nil, &RequestFailedError{StatusCode: http.StatusOK, Err: failure}\n"
        + "\t}\n"
        + "\tvar result T\n"
        + "\tif o.resourcePath == \"\" {\n"
        + "\t\treturn &result, nil\n"
        + "\t}\n"
        + "\tif err := call(ctx, o.transport, \"GET\", o.resourcePath, nil, &result); err != nil {\n"
        + "\t\treturn nil, err\n"
        + "\t}\n"
        + "\treturn &result, nil\n"
        + "}\n"
        + "\n"
        + "// ListOptions is how many resources a listing may examine. ⚠ Top is a cap the platform clamps and not a\n"
        + "// promise: the filter runs once per member, so it bounds the work and not the number of results.\n"
        + "type ListOptions struct {\n"
        + "\t// Zero sends nothing.\n"
        + "\tTop int\n"
        + "}\n"
        + "\n"
        + "// Page is one page of a collection — docs/plan/08 § The read path.\n"
        + "type Page[T any] struct {\n"
        + "\t// The resources on this page, ordered by id.\n"
        + "\tValue []T `json:\"value\"`\n"
        + "\t// ⚠ Absent on the last page. Stop when it is absent, never when a page is smaller than you asked\n"
        + "\t// for: a listing runs a permission check per member and the page is clamped.\n"
        + "\tNextLink *string `json:\"nextLink,omitempty\"`\n"
        + "}\n"
        + "\n"
        + "// Pager walks a collection page by page: More says whether NextPage has anything left to fetch.\n"
        + "type Pager[T any] struct {\n"
        + "\ttransport Transport\n"
        + "\tnext      *Request\n"
        + "}\n"
        + "\n"
        + "func newPager[T any](transport Transport, path string, options *ListOptions) *Pager[T] {\n"
        + "\t// ⚠ $top carries its sigil, which is what the gateway reads; a gateway IGNORES a query parameter it\n"
        + "\t// does not recognise, so a misspelling here is a 200 holding page one, for ever. The next page's\n"
        + "\t// $skipToken comes back inside nextLink and is sent as the path and query of that link.\n"
        + "\tquery := url.Values{}\n"
        + "\tif options != nil && options.Top > 0 {\n"
        + "\t\tquery.Set(\"$top\", strconv.Itoa(options.Top))\n"
        + "\t}\n"
        + "\treturn &Pager[T]{transport: transport, next: &Request{Method: \"GET\", Path: path, Query: query}}\n"
        + "}\n"
        + "\n"
        + "// More reports whether a page remains to be fetched. True before the first page.\n"
        + "func (p *Pager[T]) More() bool {\n"
        + "\treturn p.next != nil\n"
        + "}\n"
        + "\n"
        + "// NextPage fetches the next page. ⚠ Calling it when More is false is a programming error and returns one.\n"
        + "func (p *Pager[T]) NextPage(ctx context.Context) (*Page[T], error) {\n"
        + "\tif p.next == nil {\n"
        + "\t\treturn nil, fmt.Errorf(\"the collection has no more pages\")\n"
        + "\t}\n"
        + "\tresponse, err := p.transport.Send(ctx, p.next)\n"
        + "\tif err != nil {\n"
        + "\t\treturn nil, err\n"
        + "\t}\n"
        + "\tif err := checkStatus(response); err != nil {\n"
        + "\t\treturn nil, err\n"
        + "\t}\n"
        + "\tvar page Page[T]\n"
        + "\tif err := decode(response, &page); err != nil {\n"
        + "\t\treturn nil, err\n"
        + "\t}\n"
        + "\tp.next = nil\n"
        + "\tif page.NextLink != nil {\n"
        + "\t\tnext, err := relative(*page.NextLink)\n"
        + "\t\tif err != nil {\n"
        + "\t\t\treturn nil, err\n"
        + "\t\t}\n"
        + "\t\tp.next = next\n"
        + "\t}\n"
        + "\treturn &page, nil\n"
        + "}\n"
        + "\n"
        + "// All fetches every remaining page and returns the items in order.\n"
        + "func (p *Pager[T]) All(ctx context.Context) ([]T, error) {\n"
        + "\tvar items []T\n"
        + "\tfor p.More() {\n"
        + "\t\tpage, err := p.NextPage(ctx)\n"
        + "\t\tif err != nil {\n"
        + "\t\t\treturn nil, err\n"
        + "\t\t}\n"
        + "\t\titems = append(items, page.Value...)\n"
        + "\t}\n"
        + "\treturn items, nil\n"
        + "}\n";

    // ── Self-check ─────────────────────────────────────────────────────────────────────────────

    /// <summary>
    ///     What this surface can get wrong, as one line per problem.
    /// </summary>
    /// <param name="files">The emitted files of one api-version.</param>
    /// <remarks>
    ///     ⚠ Narrower than a compiler, and honest about it: every type the client names in a
    ///     signature is one the package declares, no type is declared twice, and every file
    ///     carries its banner. The <c>Generated Go SDK compiles</c> gate is the compiler.
    /// </remarks>
    public static ImmutableArray<string> Problems(ImmutableSortedDictionary<string, string> files) {
        ArgumentNullException.ThrowIfNull(files);

        var problems = new List<string>();
        var models = files.FirstOrDefault(static x => x.Key.EndsWith("/models.go", StringComparison.Ordinal)).Value;
        var client = files.FirstOrDefault(static x => x.Key.EndsWith("/client.go", StringComparison.Ordinal)).Value;
        var runtime = files.FirstOrDefault(static x => x.Key.EndsWith("/runtime.go", StringComparison.Ordinal)).Value;

        if (models is null || client is null || runtime is null) {
            problems.Add(
                "the package is missing models.go, client.go or runtime.go, so the emitter produced something nobody can build."
            );
            return [.. problems];
        }

        var declared = new List<string>();

        foreach (var line in (models + "\n" + client + "\n" + runtime).Split('\n')) {
            if (line.StartsWith("type ", StringComparison.Ordinal)) {
                var name = line[5..].Split(' ', '[')[0];
                declared.Add(name);
            }
        }

        foreach (var duplicate in declared.GroupBy(static x => x, StringComparer.Ordinal)
                     .Where(static x => x.Count() > 1)) {
            problems.Add(
                $"the package declares the type '{duplicate.Key}' {duplicate.Count()} times; Go refuses the redeclaration."
            );
        }

        var exported = declared.ToHashSet(StringComparer.Ordinal);

        // A model reaches the client only through a signature — `(*XResource, error)`,
        // `data XData`, `content XContent`, `Operation[XResource]` — and each of those suffixes is
        // one the models file declares.
        foreach (var line in client.Split('\n')) {
            if (!line.StartsWith("func ", StringComparison.Ordinal)) {
                continue;
            }

            foreach (var token in line.Split(' ', '(', ')', '*', '[', ']', ',')) {
                if (token.Length > 0
                    && char.IsAsciiLetterUpper(token[0])
                    && (token.EndsWith("Resource", StringComparison.Ordinal)
                        || token.EndsWith("Data", StringComparison.Ordinal)
                        || token.EndsWith("Content", StringComparison.Ordinal)
                        || token.EndsWith("Result", StringComparison.Ordinal))
                    && !exported.Contains(token)) {
                    problems.Add(
                        $"client.go names '{token}' in a signature and the package does not declare it; the module fails to build."
                    );
                }
            }
        }

        foreach (var file in files) {
            if (!file.Value.Contains("DO NOT EDIT", StringComparison.Ordinal)) {
                problems.Add(
                    $"'{file.Key}' carries no generator banner; a reader who opens an unmarked file is a reader who edits it."
                );
            }
        }

        problems.Sort(StringComparer.Ordinal);
        return [.. problems.Distinct(StringComparer.Ordinal)];
    }

    // ── Small shared machinery ─────────────────────────────────────────────────────────────────

    static string Head(string version) =>
        Banner
        + "\n// @generated from the published OpenAPI document openapi/"
        + version
        + ".json — docs/plan/21 § Generation's one hop.\n"
        + "// ./build.sh Generate overwrites this file and ./build.sh Architecture fails on a difference.\n";

    static string ScopeContent(DocumentScope scope) => SdkEmitter.Pascal(scope.Kind) + "CreateContent";

    /// <summary>
    ///     The field a scope's client takes on <c>Client</c> — <c>Tenants</c>, <c>Subscriptions</c>,
    ///     <c>ResourceGroups</c>.
    /// </summary>
    static string ScopeClientField(DocumentScope scope) => SdkEmitter.Pascal(scope.Kind) + "s";

    /// <summary>
    ///     A type's one-sentence summary as a sentence that follows another, or nothing — never a trailing space gofmt
    ///     would strip.
    /// </summary>
    static string Summary(DocumentType type) => type.Summary.Length > 0 ? " " + Comment(type.Summary) : string.Empty;

    /// <summary>The field a resource type takes on its provider's group — <c>ManagedClustersAgentPools</c>.</summary>
    static string TypeField(string typePath) => string.Concat(typePath.Split('/').Select(SdkEmitter.Pascal));

    /// <summary>A placeholder as a Go parameter — <c>tenantID</c>.</summary>
    static string Parameter(string placeholder) {
        var name = GoName(placeholder);

        return char.ToLowerInvariant(name[0]) + name[1..];
    }

    /// <summary>A wire name as an exported Go identifier, with Go's spelling of a trailing <c>Id</c>.</summary>
    static string GoName(string wireName) {
        var pascal = SdkEmitter.Pascal(wireName);

        return pascal.EndsWith("Id", StringComparison.Ordinal) ? pascal[..^2] + "ID" : pascal;
    }

    /// <summary>A Go interpreted string literal.</summary>
    static string Quote(string value) =>
        "\""
        + value.Replace("\\", "\\\\", StringComparison.Ordinal)
            .Replace("\"", "\\\"", StringComparison.Ordinal)
            .Replace("\r\n", " ", StringComparison.Ordinal)
            .Replace("\n", " ", StringComparison.Ordinal)
        + "\"";

    /// <summary>Text that is safe after <c>//</c>, on one line.</summary>
    static string Comment(string value) =>
        value.Replace("\r\n", " ", StringComparison.Ordinal).Replace("\n", " ", StringComparison.Ordinal);
}
