        + "const APIVersion = "
        + Quote(version)
        + "\n"
        + "\n"
        + "// Request is one request the client wants made. The path has every placeholder filled and every\n"
        + "// segment encoded. ⚠ api-version is NOT in Query: the transport puts it on every request, so no\n"
        + "// call site can forget it.\n"
