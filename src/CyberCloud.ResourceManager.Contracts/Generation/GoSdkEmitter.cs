            .Append(
                "func (c *OperationsClient) Get(ctx context.Context, operationID string) (*OperationStatus, error) {\n"
            )
            .Append(Read("GET", PathExpression(OperationPath), "nil", "OperationStatus"));

    static void AppendScopeClient(StringBuilder built, DocumentScope scope) {
        var name = ScopeClientField(scope) + "Client";
        var placeholders = DocumentReader.PlaceholdersOf(scope.Path);
        var parameters = Parameters(placeholders);

        built.Append("\n// ")
            .Append(name)
            .Append(" reads ")
            .Append(Comment(scope.DisplayPlural.ToLowerInvariant()))
            .Append(". ")
            .Append(Comment(scope.Summary))
            .Append('\n')
            .Append("type ")
            .Append(name)
            .Append(" struct {\n\ttransport Transport\n}\n\n")
            .Append("// Get reads one ")
            .Append(Comment(scope.DisplayName.ToLowerInvariant()))
            .Append(".\n")
            .Append("func (c *")
            .Append(name)
            .Append(") Get(ctx context.Context")
            .Append(parameters)
            .Append(") (*ScopeResource, error) {\n")
            .Append(Read("GET", PathExpression(scope.Path), "nil", "ScopeResource"));

        if (scope.CollectionPath.Length > 0) {
            // Emitted only when the document declares the collection, as a resource type's List is
            // — the tenant has none. The same Pager a resource listing walks, over ScopeResource.
            var collectionParameters = Parameters(DocumentReader.PlaceholdersOf(scope.CollectionPath));

            built.Append("\n// List pages through the ")
                .Append(Comment(scope.DisplayPlural.ToLowerInvariant()))
                .Append(" the caller may read. ⚠ A short page never means \"that is all there is\".\n")
                .Append("func (c *")
                .Append(name)
                .Append(") List(")
                .Append(collectionParameters.TrimStart(',', ' '))
                .Append(collectionParameters.Length > 0 ? ", " : string.Empty)
                .Append("options *ListOptions) *Pager[ScopeResource] {\n")
                .Append("\tpath := ")
                .Append(PathExpression(scope.CollectionPath))
                .Append('\n')
                .Append("\treturn newPager[ScopeResource](c.transport, path, options)\n}\n");
        }

        if (!scope.Creatable) {
            built.Append(
                "\n// ⚠ There is no Create, and the absence is the contract: a request's tenant is resolved from its\n"
            )
                .Append("// token, so a call creating another tenant is refused before routing runs.\n");

            return;
        }

        built.Append("\n// Create creates one ")
            .Append(Comment(scope.DisplayName.ToLowerInvariant()))
            .Append(
                ", or returns the existing one unchanged. ⚠ 201 the first time and 200 on a repeat, and no operation to poll.\n"
            )
            .Append("func (c *")
            .Append(name)
            .Append(") Create(ctx context.Context")
            .Append(parameters)
            .Append(", content ")
            .Append(ScopeContent(scope))
            .Append(") (*ScopeResource, error) {\n")
            .Append(Read("PUT", PathExpression(scope.Path), "content", "ScopeResource"));
    }

    /// <summary>
    ///     One client per namespace of scope objects — <c>PolicyClient</c> — with a method per object,
    ///     scope and verb.
    /// </summary>
    /// <remarks>
    ///     ⚠ No <c>Begin*</c> and no <c>Operation</c>: a write converges before the call returns — the
    ///     scope client's rule, for the scope client's reason.
    /// </remarks>
    static void AppendScopeObjectClient(StringBuilder built, string group, List<DocumentScopeObject> objects) {
        var name = SdkEmitter.Pascal(group) + "Client";

        built.Append("\n// ")
            .Append(name)
            .Append(" reads and writes the objects under ")
            .Append(objects[0].ProviderNamespace)
            .Append(", on every scope that takes them — docs/plan/08 § Policy.\n")
            .Append("type ")
            .Append(name)
            .Append(" struct {\n\ttransport Transport\n}\n");

        foreach (var scoped in objects) {
            var on = Comment(scoped.DisplayName.ToLowerInvariant()) + " on a " + CliEmitter.Kebab(scoped.Scope).Replace('-', ' ');
            var collectionParameters = Parameters(DocumentReader.PlaceholdersOf(scoped.CollectionPath));

            built.Append("\n// List")
                .Append(scoped.PluralStem)
                .Append(" pages through the ")
                .Append(Comment(scoped.DisplayPlural.ToLowerInvariant()))
                .Append(" on a ")
                .Append(CliEmitter.Kebab(scoped.Scope).Replace('-', ' '))
                .Append(". ⚠ A short page never means \"that is all there is\".\n")
                .Append("func (c *")
                .Append(name)
                .Append(") List")
                .Append(scoped.PluralStem)
                .Append('(')
                .Append(collectionParameters.TrimStart(',', ' '))
                .Append(collectionParameters.Length > 0 ? ", " : string.Empty)
                .Append("options *ListOptions) *Pager[")
                .Append(scoped.ModelName)
                .Append("] {\n")
                .Append("\tpath := ")
                .Append(PathExpression(scoped.CollectionPath))
                .Append('\n')
                .Append("\treturn newPager[")
                .Append(scoped.ModelName)
                .Append("](c.transport, path, options)\n}\n");

            if (scoped.Path.Length == 0) {
                continue;
            }

            var parameters = Parameters(DocumentReader.PlaceholdersOf(scoped.Path));
            var path = PathExpression(scoped.Path);

            built.Append("\n// Get")
                .Append(scoped.SingularStem)
                .Append(" reads one ")
                .Append(on)
                .Append(".\n")
                .Append("func (c *")
                .Append(name)
                .Append(") Get")
                .Append(scoped.SingularStem)
                .Append("(ctx context.Context")
                .Append(parameters)
                .Append(") (*")
                .Append(scoped.ModelName)
                .Append(", error) {\n")
                .Append(Read("GET", path, "nil", scoped.ModelName));

            if (!scoped.Writable) {
                continue;
            }

            built.Append("\n// CreateOrUpdate")
                .Append(scoped.SingularStem)
                .Append(" creates or replaces one ")
                .Append(on)
                .Append(", written whole. ⚠ 201 the first time and 200 after, and no operation to poll.\n")
                .Append("func (c *")
                .Append(name)
                .Append(") CreateOrUpdate")
                .Append(scoped.SingularStem)
                .Append("(ctx context.Context")
                .Append(parameters)
                .Append(", content ")
                .Append(scoped.ContentName)
                .Append(") (*")
                .Append(scoped.ModelName)
                .Append(", error) {\n")
                .Append(Read("PUT", path, "content", scoped.ModelName))
                .Append("\n// Delete")
                .Append(scoped.SingularStem)
                .Append(" deletes one ")
                .Append(on)
                .Append(". An object already gone is a success.\n")
                .Append("func (c *")
                .Append(name)
                .Append(") Delete")
                .Append(scoped.SingularStem)
                .Append("(ctx context.Context")
                .Append(parameters)
                .Append(") error {\n")
                .Append("\tpath := ")
                .Append(path)
                .Append('\n')
                .Append("\treturn call(ctx, c.transport, \"DELETE\", path, nil, nil)\n}\n");
        }
    }

    static void AppendProviderGroup(
        StringBuilder built,
        string providerNamespace,
        List<DocumentType> types,
        ImmutableDictionary<string, string> names
    ) {
        var segment = SdkEmitter.Pascal(providerNamespace.Split('.')[^1]);
        var taken = new Dictionary<string, string>(StringComparer.Ordinal);
        var ordered = types.OrderBy(static x => x.TypePath, StringComparer.Ordinal).ToList();

        var members = new List<(string Field, string Type, string Value)>();

        foreach (var type in ordered) {
            var field = TypeField(type.TypePath);

            if (taken.TryGetValue(field, out var other)) {
                throw new InvalidOperationException(
                    $"'{type.ResourceType}' and '{other}' both generate the Go field '{field}' on {segment}Provider. "
                    + "Two type paths that differ only in case or punctuation are one Go name."
                );
            }

            taken[field] = type.ResourceType;
            members.Add(
                (field, "*" + names[type.ResourceType] + "Client",
                    "&" + names[type.ResourceType] + "Client{transport: transport}")
            );
        }

        built.Append("\n// ")
            .Append(segment)
            .Append("Provider holds the resource types of ")
            .Append(Comment(providerNamespace))
            .Append(".\n");

        AppendHolder(
            built,
            segment + "Provider",
            "new" + segment + "Provider",
            "builds the group's clients over one transport.",
            members
        );
    }

    static void AppendTypeClient(StringBuilder built, DocumentType type, string model) {
        var placeholders = DocumentReader.PlaceholdersOf(type.Path);
        var parameters = Parameters(placeholders);
        var path = PathExpression(type.Path);
        var client = model + "Client";

        built.Append("\n// ")
            .Append(client)
            .Append(" is ")
            .Append(Comment(type.DisplayPlural.ToLowerInvariant()))
            .Append(" — ")
            .Append(type.ResourceType)
            .Append('.')
            .Append(Summary(type))
            .Append('\n')
            .Append("type ")
            .Append(client)
            .Append(" struct {\n\ttransport Transport\n}\n");

        built.Append("\n// Get reads one ")
            .Append(Comment(type.DisplayName))
            .Append(".\n")
            .Append("func (c *")
            .Append(client)
            .Append(") Get(ctx context.Context")
            .Append(parameters)
            .Append(") (*")
            .Append(model)
            .Append("Resource, error) {\n")
            .Append(Read("GET", path, "nil", model + "Resource"));

        built.Append("\n// BeginCreateOrUpdate creates or replaces one ")
            .Append(Comment(type.DisplayName))
            .Append(". ⚠ Long-running: Wait on the result.\n")
            .Append("func (c *")
            .Append(client)
            .Append(") BeginCreateOrUpdate(ctx context.Context")
            .Append(parameters)
            .Append(", data ")
            .Append(model)
            .Append("Data) (*Operation[")
            .Append(model)
            .Append("Resource], error) {\n")
            .Append("\tpath := ")
            .Append(path)
            .Append('\n')
            .Append("\treturn begin[")
            .Append(model)
            .Append("Resource](ctx, c.transport, \"PUT\", path, data, path)\n}\n");

        built.Append("\n// BeginUpdate amends one ")
            .Append(Comment(type.DisplayName))
            .Append(". A merge patch: what is not set is not changed.\n")
            .Append("func (c *")
            .Append(client)
            .Append(") BeginUpdate(ctx context.Context")
            .Append(parameters)
            .Append(", data ")
            .Append(model)
            .Append("Data) (*Operation[")
            .Append(model)
            .Append("Resource], error) {\n")
            .Append("\tpath := ")
            .Append(path)
            .Append('\n')
            .Append("\treturn begin[")
            .Append(model)
            .Append("Resource](ctx, c.transport, \"PATCH\", path, data, path)\n}\n");

        built.Append("\n// BeginDelete deletes one ")
            .Append(Comment(type.DisplayName))
            .Append('.')
            .Append(
                type.SoftDeleteDays > 0
                    ? " ⚠ Recoverable for " + DocumentReader.Count(type.SoftDeleteDays) + " day(s)."
                    : " ⚠ Permanent: this type declares no soft-delete window."
            )
            .Append('\n')
            .Append("func (c *")
            .Append(client)
            .Append(") BeginDelete(ctx context.Context")
            .Append(parameters)
            .Append(") (*Operation[struct{}], error) {\n")
            .Append("\tpath := ")
            .Append(path)
            .Append('\n')
            .Append("\treturn begin[struct{}](ctx, c.transport, \"DELETE\", path, nil, \"\")\n}\n");

        if (type.CollectionPath.Length > 0) {
            var collectionParameters = Parameters(DocumentReader.PlaceholdersOf(type.CollectionPath));

            built.Append("\n// List pages through the ")
                .Append(Comment(type.DisplayPlural))
                .Append(" in a resource group. ⚠ A short page never means \"that is all there is\".\n")
                .Append("func (c *")
                .Append(client)
                .Append(") List(")
                .Append(collectionParameters.TrimStart(',', ' '))
                .Append(collectionParameters.Length > 0 ? ", " : string.Empty)
                .Append("options *ListOptions) *Pager[")
                .Append(model)
                .Append("Resource] {\n")
                .Append("\tpath := ")
                .Append(PathExpression(type.CollectionPath))
                .Append('\n')
                .Append("\treturn newPager[")
                .Append(model)
                .Append("Resource](c.transport, path, options)\n}\n");
        }

        foreach (var action in type.Actions) {
            var method = SdkEmitter.Pascal(action.Name);
            var content = action.Request is null ? string.Empty : ", content " + model + method + "Content";
            var body = action.Request is null ? "nil" : "content";
            var actionPath = PathExpression(type.Path + "/" + action.Name);
            var doc = Comment(action.Name)
                + " — permission '"
                + Comment(action.Permission)
                + "'."
                + (action.Secret ? " ⚠ The response carries secret material." : string.Empty);

            // ⚠ A purge ends the resource, so its Operation is BeginDelete's: Wait reads nothing, because
            // the GET the resource-returning shape sends afterwards is a 404 for a purge that worked.
            // Read off the document (DocumentAction.RemovesResource), never off the name here.
            if (action is { LongRunning: true, RemovesResource: true }) {
                built.Append("\n// Begin")
                    .Append(method)
                    .Append(" runs ")
                    .Append(doc)
                    .Append(
                        " ⚠ Long-running, and it removes the resource: Wait reads nothing afterwards, because there is nothing left to read.\n"
                    )
                    .Append("func (c *")
                    .Append(client)
                    .Append(") Begin")
                    .Append(method)
                    .Append("(ctx context.Context")
                    .Append(parameters)
                    .Append(content)
                    .Append(") (*Operation[struct{}], error) {\n")
                    .Append("\tpath := ")
                    .Append(actionPath)
                    .Append('\n')
                    .Append("\treturn begin[struct{}](ctx, c.transport, \"POST\", path, ")
                    .Append(body)
                    .Append(", \"\")\n}\n");

                continue;
            }

            if (action.LongRunning) {
                built.Append("\n// Begin")
                    .Append(method)
                    .Append(" runs ")
                    .Append(doc)
                    .Append(" ⚠ Long-running: Wait resolves to the resource afterwards.\n")
                    .Append("func (c *")
                    .Append(client)
                    .Append(") Begin")
                    .Append(method)
                    .Append("(ctx context.Context")
                    .Append(parameters)
                    .Append(content)
                    .Append(") (*Operation[")
                    .Append(model)
                    .Append("Resource], error) {\n")
                    .Append("\tpath := ")
                    .Append(path)
                    .Append('\n')
                    .Append("\treturn begin[")
                    .Append(model)
                    .Append("""Resource](ctx, c.transport, "POST", path+""")
                    .Append(Quote("/" + action.Name))
                    .Append(", ")
                    .Append(body)
                    .Append(", path)\n}\n");

                continue;
            }

            if (action.Response is null) {
                built.Append("\n// ")
                    .Append(method)
                    .Append(" runs ")
                    .Append(doc)
                    .Append('\n')
                    .Append("func (c *")
                    .Append(client)
                    .Append(") ")
                    .Append(method)
                    .Append("(ctx context.Context")
                    .Append(parameters)
                    .Append(content)
                    .Append(") error {\n")
                    .Append("\tpath := ")
                    .Append(actionPath)
                    .Append('\n')
                    .Append("\treturn call(ctx, c.transport, \"POST\", path, ")
                    .Append(body)
                    .Append(", nil)\n}\n");

                continue;
            }

            built.Append("\n// ")
                .Append(method)
                .Append(" runs ")
                .Append(doc)
                .Append('\n')
                .Append("func (c *")
                .Append(client)
                .Append(") ")
                .Append(method)
                .Append("(ctx context.Context")
                .Append(parameters)
                .Append(content)
                .Append(") (*")
                .Append(model)
                .Append(method)
                .Append("Result, error) {\n")
                .Append(Read("POST", actionPath, body, model + method + "Result"));
        }
    }

    /// <summary>
    ///     The body of a method that reads one typed result: the path, the call, the checked error.
    /// </summary>
    /// <remarks>
    ///     ⚠ The path goes into a local first, on every method, because gofmt spaces a binary
    ///     <c>+</c> at statement level and compacts it inside a call's argument list — and a
    ///     checked-in file that gofmt would rewrite is one a reader's editor rewrites on open.
    /// </remarks>
    static string Read(string method, string pathExpression, string body, string result) =>
        "\tpath := "
        + pathExpression
        + "\n"
        + "\tvar result "
        + result
        + "\n"
        + "\tif err := call(ctx, c.transport, "
        + Quote(method)
        + ", path, "
        + body
        + ", &result); err != nil {\n"
        + "\t\treturn nil, err\n"
        + "\t}\n"
        + "\treturn &result, nil\n"
        + "}\n";

    /// <summary>The parameter list a path's placeholders need, each a <c>string</c>, with a leading comma.</summary>
    static string Parameters(ImmutableArray<string> placeholders) =>
        placeholders.IsEmpty ? string.Empty : ", " + string.Join(", ", placeholders.Select(Parameter)) + " string";

    /// <summary>A path template as a Go expression with each placeholder encoded.</summary>
    static string PathExpression(string path) {
        var built = new StringBuilder("\"");

        for (var i = 0; i < path.Length; i++) {
            if (path[i] != '{') {
                if (path[i] is '"' or '\\') {
                    built.Append('\\');
                }

                built.Append(path[i]);
                continue;
            }

            var close = path.IndexOf('}', i + 1);

            if (close < 0) {
                built.Append(path[i]);
                continue;
            }

            built.Append("\" + segment(").Append(Parameter(path[(i + 1)..close])).Append(") + \"");
            i = close;
        }

        return built.Append('"').ToString().Replace(" + \"\"", string.Empty, StringComparison.Ordinal);
    }

