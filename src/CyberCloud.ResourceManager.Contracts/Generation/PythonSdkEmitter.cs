    static string Client(
        string version,
        JsonObject document,
        ImmutableArray<DocumentType> types,
        ImmutableArray<DocumentScope> scopes,
        ImmutableDictionary<string, string> names
    ) {
        var built = new StringBuilder(Head(version));
        var polls = document["paths"]?[OperationPath] is JsonObject;

        built.Append("\"\"\"The public REST API at api-version ")
            .Append(version)
            .Append(", typed: one client per resource type, grouped by provider.\"\"\"\n\n")
            .Append("from __future__ import annotations\n\n")
            .Append("from typing import Optional\n")
            .Append("from urllib.parse import quote\n\n")
            .Append("from ._runtime import Operation, Pager, Request, Transport, raise_for_status, wire_of\n")
            .Append("from .models import (\n");

        var imported = new SortedSet<string>(StringComparer.Ordinal);

        if (polls) {
            imported.Add("OperationStatus");
        }

        if (!scopes.IsEmpty) {
            imported.Add("ScopeResource");
        }

        foreach (var scope in scopes.Where(x => x.Creatable)) {
            imported.Add(ScopeContent(scope));
        }

        foreach (var type in types) {
            var model = names[type.ResourceType];
            imported.Add(model + "Data");
            imported.Add(model + "Resource");

            foreach (var action in type.Actions) {
                if (action.Request is not null) {
                    imported.Add(model + SdkEmitter.Pascal(action.Name) + "Content");
                }

                if (action.Response is not null) {
                    imported.Add(model + SdkEmitter.Pascal(action.Name) + "Result");
                }
            }
        }

        foreach (var name in imported) {
            built.Append("    ").Append(name).Append(",\n");
        }

        built.Append(")\n\n")
            .Append("GENERATED_API_VERSION = ").Append(Quote(version)).Append('\n')
            .Append("\"\"\"The api-version this client was generated at. The transport sends it on every request.\"\"\"\n\n\n")
            .Append("def _segment(value: str) -> str:\n")
            .Append("    \"\"\"Percent-encodes one path segment. ⚠ A name is caller data and a '/' in one would forge a path.\"\"\"\n")
            .Append("    return quote(value, safe=\"\")\n\n\n")
            .Append("def _nothing(wire: object) -> None:\n")
            .Append("    \"\"\"What a delete resolves to: the resource is gone, so there is nothing to read.\"\"\"\n")
            .Append("    return None\n");

        if (polls) {
            AppendOperationsClient(built);
        }

        foreach (var scope in scopes) {
            AppendScopeClient(built, scope);
        }

        var groups = types.GroupBy(x => x.ProviderNamespace, StringComparer.Ordinal)
            .OrderBy(x => x.Key, StringComparer.Ordinal)
            .ToList();

        foreach (var group in groups) {
            foreach (var type in group) {
                AppendTypeClient(built, type, names[type.ResourceType]);
            }

            AppendProviderGroup(built, group.Key, group.ToList(), names);
        }

        AppendRootClient(built, version, polls, scopes, groups);

        return built.ToString();
    }

