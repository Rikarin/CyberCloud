    /// <summary>A wire name as a Python member — <c>snake_case</c>, and never a keyword.</summary>
    /// <remarks>
    ///     ⚠ <c>type</c> is a soft keyword since 3.12 and is exempt: the envelope's <c>type</c>
    ///     member is what every reader expects, and a soft keyword is a legal attribute name.
    /// </remarks>
    static string Identifier(string wireName) {
        var snake = Snake(wireName);

        return Keywords.Contains(snake) && snake != "type" ? snake + "_" : snake;
    }

    /// <summary>Any identifier-ish string as <c>snake_case</c>, invariantly.</summary>
    internal static string Snake(string value) {
        var built = new StringBuilder(value.Length + 4);

        for (var i = 0; i < value.Length; i++) {
            var current = value[i];

            if (!char.IsLetterOrDigit(current)) {
                if (built.Length > 0 && built[^1] != '_') {
                    built.Append('_');
                }

                continue;
            }

            if (char.IsUpper(current) && built.Length > 0 && built[^1] != '_') {
                var previous = value[i - 1];
                var next = i + 1 < value.Length ? value[i + 1] : '\0';

                // A boundary before an upper that follows a lower or digit (storageGb → storage_gb),
                // and before the last upper of a run when a lower follows it (SQLServer → sql_server).
                if (char.IsLower(previous) || char.IsDigit(previous) || (char.IsUpper(previous) && char.IsLower(next))) {
                    built.Append('_');
                }
            }

            built.Append(char.ToLowerInvariant(current));
        }

        var result = built.ToString().TrimEnd('_');

        if (result.Length == 0) {
            return "value";
        }

        return char.IsAsciiDigit(result[0]) ? "n" + result : result;
    }

    /// <summary>A Python double-quoted string literal.</summary>
    static string Quote(string value) =>
        "\""
        + value.Replace("\\", "\\\\", StringComparison.Ordinal)
            .Replace("\"", "\\\"", StringComparison.Ordinal)
            .Replace("\r\n", " ", StringComparison.Ordinal)
            .Replace("\n", " ", StringComparison.Ordinal)
        + "\"";

    /// <summary>Text that is safe inside a triple-quoted docstring, on one line.</summary>
    static string Docstring(string value) =>
        value.Replace("\\", "\\\\", StringComparison.Ordinal)
            .Replace("\"\"\"", "\\\"\\\"\\\"", StringComparison.Ordinal)
            .Replace("\r\n", " ", StringComparison.Ordinal)
            .Replace("\n", " ", StringComparison.Ordinal)
            .TrimEnd('"');

    /// <summary>Text that is safe after <c>#</c>, on one line.</summary>
    static string Comment(string value) =>
        value.Replace("\r\n", " ", StringComparison.Ordinal).Replace("\n", " ", StringComparison.Ordinal);
