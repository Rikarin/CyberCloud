using System.Collections.Immutable;
using System.Text;
using System.Text.Json.Nodes;

namespace CyberCloud.ResourceManager.Contracts.Generation;

/// <summary>
///     The Python SDK: ADR-012's surfaces, one more language over — issue #40.
/// </summary>
/// <remarks>
///     <para>
///         ⚠
///         <b>
///             THIS READS THE PUBLISHED OPENAPI DOCUMENT, NOT THE REGISTRY, AND THAT IS THE ONE
///             DECISION THE ISSUE SAID WAS NOT MECHANICAL.
///         </b> docs/plan/21 § Generation's one hop is what makes the compatibility diff over
///         the published document cover every client at once; an emitter that read the registry
///         would sit outside that guarantee, describing a field the published contract does not
///         have with no gate to notice. <see cref="TypeScriptEmitter" /> made the same call for
///         issue #21 and this emitter walks the same <see cref="DocumentReader" />.
///     </para>
///     <para>
///         <b>What is emitted, per api-version</b> — a subpackage <c>cybercloud.v{version}</c>:
///         <c>models.py</c> with one dataclass per schema and a <c>Literal</c> alias per closed set,
///         nested exactly as the wire is (a container is a nested class, so every leaf keeps the
///         member name the document gives it — docs/plan/21 § Generation's conventions table, the
///         #79 convention); <c>client.py</c> with one class per resource type grouped under its
///         provider, <c>begin_*</c> for every long-running verb and a pager for every collection;
///         <c>_runtime.py</c> with the transport seam, a standard-library transport, the one error
///         shape, the operation poller, and the <c>$skipToken</c> pager.
///     </para>
///     <para>
///         ⚠ <b>Dataclasses and explicit <c>to_wire</c>/<c>from_wire</c>, not reflection over
///         type hints.</b> The wire name of a member and its Python name differ
///         (<c>clusterId</c>, <c>cluster_id</c>), a leaf named <c>class</c> exists in the Cache
///         provider's document and cannot be a bare identifier, and a read-only member must be
///         read and never written. Each of those is a rule a generated method states in one line
///         and a reflective serializer would have to be configured to know. The same reasoning
///         gave the .NET SDK a nested class per container rather than a flat one with renamed
///         members.
///     </para>
///     <para>
///         ⚠ <b>A closed set is a <c>Literal</c>, not an <c>Enum</c>.</b> A type checker refuses a
///         typo either way; a <c>str</c> subclass of <c>Enum</c> would also refuse, at run time, a
///         value a newer server adds to a read-only vocabulary, and would need a member name
///         computed from every value — <c>allkeys-lru</c>, <c>s1.small</c> — with its own
///         collisions to refuse. The TypeScript client made the same choice for a different
///         reason (bundle bytes); the outcome is the same shape.
///     </para>
///     <para>
///         ⚠ <b>What this cannot check, said plainly.</b> Nothing in the .NET build runs Python.
///         <see cref="Problems" /> is the cheap self-check — every model the client names is one
///         the models declare, every file carries its banner — and the <c>Generated Python SDK
///         compiles</c> gate in <c>build/Build.Architecture.cs</c> hands the checked-in package to
///         <c>python -m compileall</c>, and to <c>mypy</c> when it is installed, reporting ○ with
///         the reason when the toolchain is absent rather than ✔.
///     </para>
/// </remarks>
public static class PythonSdkEmitter {
    /// <summary>The subdirectory of <c>generated/</c> the package is checked in at.</summary>
    public const string DirectoryName = "sdk-python";

    /// <summary>The importable package.</summary>
    public const string PackageName = "cybercloud";

    /// <summary>The banner every emitted file carries in its first line.</summary>
    const string Banner =
        "# @generated by CyberCloud.ResourceManager.Contracts.Generation.PythonSdkEmitter — DO NOT EDIT.";

    /// <summary>
    ///     Python names a resource type's group is refused, because the client already declares
    ///     an attribute of that name.
    /// </summary>
    static readonly ImmutableHashSet<string> ReservedGroups =
        ["operations", "tenants", "subscriptions", "resource_groups"];

    /// <summary>The subpackage one api-version's client lives in — <c>v2026_08_01</c>.</summary>
    /// <param name="apiVersion">The api-version, as the document spells it.</param>
    /// <remarks>
    ///     ⚠ A leading <c>v</c> because a Python module cannot start with a digit, and underscores
    ///     because a hyphen is a minus sign.
    /// </remarks>
    public static string ModuleOf(string apiVersion) {
        ArgumentNullException.ThrowIfNull(apiVersion);

        return "v" + apiVersion.Replace('-', '_');
    }

    /// <summary>
    ///     The files every run writes once, whatever the api-versions are — the package manifest,
    ///     the root package, and the <c>py.typed</c> marker.
    /// </summary>
    /// <param name="apiVersions">Every api-version emitted, so the root package can name them.</param>
    /// <returns>The files, keyed by their path under <c>generated/sdk-python</c>.</returns>
    public static ImmutableSortedDictionary<string, string> Root(IEnumerable<string> apiVersions) {
        ArgumentNullException.ThrowIfNull(apiVersions);

        var versions = apiVersions.OrderBy(x => x, StringComparer.Ordinal).ToList();
        var root = new StringBuilder(Banner);

        root.Append("\n# ./build.sh Generate overwrites this file and ./build.sh Architecture fails on a difference.\n")
            .Append("\"\"\"The CyberCloud SDK, generated from the published OpenAPI documents (ADR-012).\n\n")
            .Append("One subpackage per api-version; import the one your platform serves:\n\n");

        foreach (var version in versions) {
            root.Append("    from cybercloud.").Append(ModuleOf(version)).Append(" import CyberCloudClient, HttpTransport\n");
        }

        root.Append("\n⚠ Every file under this package is generated. docs/plan/21 § Generation.\n\"\"\"\n\n")
            .Append("API_VERSIONS = (")
            .Append(string.Join(", ", versions.Select(Quote)))
            // A one-element tuple needs its trailing comma, or it is a parenthesised string.
            .Append(versions.Count == 1 ? ",)" : ")")
            .Append("\n\"\"\"Every api-version this package carries a client for, oldest first.\"\"\"\n");

        var manifest = Banner
            + "\n# ./build.sh Generate overwrites this file and ./build.sh Architecture fails on a difference.\n"
            + "[build-system]\n"
            + "requires = [\"setuptools>=61\"]\n"
            + "build-backend = \"setuptools.build_meta\"\n"
            + "\n"
            + "[project]\n"
            + "name = \"cybercloud-sdk\"\n"
            + "version = \"0.0.0\"\n"
            + "description = \"The CyberCloud SDK, generated from the published OpenAPI documents. Not yet published — docs/plan/21 § Other SDKs.\"\n"
            + "requires-python = \">=3.10\"\n"
            + "dependencies = []\n"
            + "\n"
            + "[tool.setuptools.packages.find]\n"
            + "include = [\"cybercloud*\"]\n"
            + "\n"
            + "[tool.mypy]\n"
            + "strict = true\n";

        return ImmutableSortedDictionary.CreateRange(
            StringComparer.Ordinal,
            new Dictionary<string, string>(StringComparer.Ordinal) {
                ["pyproject.toml"] = manifest,
                [PackageName + "/__init__.py"] = root.ToString(),
                // ⚠ PEP 561: without this marker mypy treats an installed copy of the package as
                // untyped and every annotation here is invisible to a consumer's type checker.
                [PackageName + "/py.typed"] = Banner + "\n"
            }
        );
    }

    /// <summary>Emits one api-version's subpackage, keyed by path under <c>generated/sdk-python</c>.</summary>
    /// <param name="document">An emitted OpenAPI document.</param>
    /// <returns>The files, ordered by path.</returns>
    public static ImmutableSortedDictionary<string, string> Emit(JsonObject document) {
        ArgumentNullException.ThrowIfNull(document);

        var version = DocumentReader.VersionOf(document);
        var types = DocumentReader.TypesOf(document);
        var scopes = DocumentReader.ScopesOf(document);
        var names = SdkEmitter.ModelNames(types);
        var module = PackageName + "/" + ModuleOf(version) + "/";
        var models = Models(version, document, types, scopes, names);

        return ImmutableSortedDictionary.CreateRange(
            StringComparer.Ordinal,
            new Dictionary<string, string>(StringComparer.Ordinal) {
                [module + "__init__.py"] = Index(version, Declared(models)),
                [module + "models.py"] = models,
                [module + "client.py"] = Client(version, document, types, scopes, names),
                [module + "_runtime.py"] = Runtime(version)
            }
        );
    }

