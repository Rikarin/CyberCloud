    /// <summary>The ten names <c>_runtime</c> and <c>client</c> put on the subpackage.</summary>
    static readonly ImmutableArray<string> RuntimeExports = [
        "API_VERSION",
        "CyberCloudClient",
        "HttpTransport",
        "Operation",
        "Page",
        "Pager",
        "Request",
        "RequestFailedError",
        "Response",
        "Transport"
    ];

    /// <summary>The subpackage's <c>__init__.py</c>: the runtime, the client and every model, re-exported by name.</summary>
    /// <param name="version">The api-version the subpackage is for.</param>
    /// <param name="models">Every name <c>models.py</c> declares, in its own <c>__all__</c> order.</param>
    /// <remarks>
    ///     ⚠ <b>The subpackage's <c>__all__</c> lists every model by name, not only the runtime
    ///     ten.</b> <c>from .models import *</c> binds the models on the subpackage, and a named
    ///     import of one works with or without this — but <c>from cybercloud.v2026_08_01 import *</c>
    ///     exports exactly what the subpackage's own <c>__all__</c> lists, and the first cut listed
    ///     ten names beside a comment calling the models "the public surface", so that import bound
    ///     no model at all. mypy reads <c>__all__</c> as a literal list and not as
    ///     <c>[*a, *models.__all__]</c>, so the list is written out rather than composed.
    /// </remarks>
    static string Index(string version, IEnumerable<string> models) {
        var built = new StringBuilder(Head(version));

        built.Append("\"\"\"The CyberCloud API at api-version ").Append(version).Append(", typed.\"\"\"\n\n")
            .Append("from ._runtime import (\n")
            .Append("    API_VERSION,\n")
            .Append("    HttpTransport,\n")
            .Append("    Operation,\n")
            .Append("    Page,\n")
            .Append("    Pager,\n")
            .Append("    Request,\n")
            .Append("    RequestFailedError,\n")
            .Append("    Response,\n")
            .Append("    Transport,\n")
            .Append(")\n")
            .Append("from .client import CyberCloudClient\n")
            .Append("from .models import *  # noqa: F401,F403 — the models are the public surface, and __all__ below names each\n\n")
            .Append("__all__ = [\n");

        foreach (var name in RuntimeExports.Concat(models).OrderBy(x => x, StringComparer.Ordinal)) {
            built.Append("    ").Append(Quote(name)).Append(",\n");
        }

        built.Append("]\n");

        return built.ToString();
    }

    // ── models.py ──────────────────────────────────────────────────────────────────────────────

    static string Models(
        string version,
        JsonObject document,
        ImmutableArray<DocumentType> types,
        ImmutableArray<DocumentScope> scopes,
        ImmutableDictionary<string, string> names
    ) {
        var built = new StringBuilder(Head(version));

        built.Append("\"\"\"Models for api-version ")
            .Append(version)
            .Append(": one class per schema, nested exactly as the wire is.\"\"\"\n\n")
            .Append("from __future__ import annotations\n\n")
            .Append("from dataclasses import dataclass, field\n")
            .Append("from typing import Any, Callable, Dict, List, Literal, Optional, TypeVar\n\n")
            .Append("Wire = Dict[str, Any]\n")
            .Append("\"\"\"A JSON object, as the wire carries it.\"\"\"\n\n")
            .Append("_T = TypeVar(\"_T\")\n\n\n")
            .Append("def _opt(wire: Wire, key: str, parse: Callable[[Wire], _T]) -> Optional[_T]:\n")
            .Append("    \"\"\"Parses a nested object when the member is present and not null.\"\"\"\n")
            .Append("    value = wire.get(key)\n")
            .Append("    return None if value is None else parse(value)\n");

        AppendErrorModels(built, document);
        AppendOperationModels(built, document);
        AppendScopeModels(built, document, scopes);
        AppendProvisioningState(built, document);

        foreach (var type in types) {
            AppendTypeModels(built, type, names[type.ResourceType]);
        }

        // ⚠ __all__ is what `from .models import *` re-exports under mypy's strict mode, which
        // treats an unlisted import as private to the module that made it. Read off the text so it
        // cannot disagree with what was declared.
        built.Append("\n\n__all__ = [\n");

        foreach (var name in Declared(built.ToString())) {
            built.Append("    ").Append(Quote(name)).Append(",\n");
        }

        built.Append("]\n");

        return built.ToString();
    }

    /// <summary>Every module-level class and <c>Literal</c> alias in a models file, in order.</summary>
    static List<string> Declared(string models) {
        var declared = new List<string>();

        foreach (var line in models.Split('\n')) {
            if (line.StartsWith("class ", StringComparison.Ordinal)) {
                declared.Add(line[6..].TrimEnd(':', ' '));
            } else if (line.Length > 0 && char.IsAsciiLetterUpper(line[0]) && line.Contains(" = ", StringComparison.Ordinal)) {
                declared.Add(line[..line.IndexOf(' ', StringComparison.Ordinal)]);
            }
        }

        return declared;
    }

    /// <summary>
    ///     The one error shape — docs/plan/08 § Errors — with the closed set of codes from the
    ///     document.
    /// </summary>
    /// <remarks>
    ///     ⚠ <c>code</c> is typed <c>str</c> and the <c>ErrorCode</c> alias holds the known values,
    ///     so <c>error.code == "QuotaExceeded"</c> and a comparison against a code a newer server
    ///     added both type-check. The .NET SDK types it the same way.
    /// </remarks>
    static void AppendErrorModels(StringBuilder built, JsonObject document) {
        var codes = DocumentReader.EnumOf(document["components"]?["schemas"]?["ErrorCode"] as JsonObject ?? []);

        built.Append("\n\nErrorCode = ");
        AppendLiteral(built, codes);
        built.Append("\n\"\"\"A stable, documented, greppable identifier. ⚠ Part of the API contract.\"\"\"\n");

        built.Append("\n\n@dataclass\n")
            .Append("class CyberCloudError:\n")
            .Append("    \"\"\"One error. docs/plan/08 § Errors.\"\"\"\n\n")
            .Append("    code: str\n")
            .Append("    message: str\n")
            .Append("    # ⚠ An RFC 6901 JSON Pointer into the request body, so a form can highlight the field.\n")
            .Append("    target: Optional[str] = None\n")
            .Append("    details: List[CyberCloudError] = field(default_factory=list)\n\n")
            .Append("    @classmethod\n")
            .Append("    def from_wire(cls, wire: Wire) -> CyberCloudError:\n")
            .Append("        return cls(\n")
            .Append("            code=wire[\"code\"],\n")
            .Append("            message=wire[\"message\"],\n")
            .Append("            target=wire.get(\"target\"),\n")
            .Append("            details=[CyberCloudError.from_wire(x) for x in wire.get(\"details\") or []],\n")
            .Append("        )\n");
    }

    /// <summary>
    ///     The poll half of docs/plan/10 § Long-running operations, over HTTP, from the document —
    ///     as the TypeScript client does, and unlike the .NET SDK, whose poller is hand-written.
    /// </summary>
    static void AppendOperationModels(StringBuilder built, JsonObject document) {
        var schemas = document["components"]?["schemas"] as JsonObject;

        if (schemas?[OpenApiEmitter.OperationStatusSchema] is not JsonObject status) {
            return;
        }

        var states = DocumentReader.EnumOf(schemas[OpenApiEmitter.OperationStateSchema] as JsonObject ?? []);

        built.Append("\n\nOperationState = ");
        AppendLiteral(built, states);
        built.Append("\n\"\"\"Azure's status vocabulary. ⚠ Terminal means Succeeded, Failed or Canceled; poll until then.\"\"\"\n");

        if (schemas[OpenApiEmitter.OperationProgressSchema] is JsonObject progress) {
            AppendPlainClass(
                built,
                "OperationProgress",
                DocumentReader.Text(progress["description"]),
                DocumentReader.LeavesOf(progress),
                default,
                writable: false
            );
        }

        // ⚠ Walked with the three $ref members written out, exactly as TypeScriptEmitter does:
        // LeavesOf reads a $ref as an untyped object, and a status typed Any is a poll nothing can
        // act on. Present or optional as x-cybercloud-read-required says.
        var served = DocumentReader.ReadRequiredOf(status);
        var members = new List<PyMember>();

        foreach (var leaf in DocumentReader.LeavesOf(status)) {
            switch (leaf.Name) {
                case "error":
                    members.Add(new(leaf.Name, "error", "CyberCloudError", false, false, "_opt(wire, \"error\", CyberCloudError.from_wire)", "Present once the status is Failed, and the reason."));
                    break;

                case "progress":
                    members.Add(
                        new(
                            leaf.Name,
                            "progress",
                            "List[OperationProgress]",
                            served.Contains(leaf.Name),
                            false,
                            "[OperationProgress.from_wire(x) for x in wire.get(\"progress\") or []]",
                            "Oldest first. What makes a nine-minute cluster creation tolerable — docs/plan/10."
                        )
                    );
                    break;

                case "status":
                    members.Add(new(leaf.Name, "status", "OperationState", true, false, "wire[\"status\"]", string.Empty));
                    break;

                default:
                    members.Add(Member(leaf with { Required = leaf.Required || served.Contains(leaf.Name) }, default, string.Empty));
                    break;
            }
        }

        AppendClassFrom(built, string.Empty, "OperationStatus", DocumentReader.Text(status["description"]), members, writable: false);
    }

    static void AppendScopeModels(StringBuilder built, JsonObject document, ImmutableArray<DocumentScope> scopes) {
        if (scopes.IsEmpty) {
            return;
        }

        var schema = document["components"]?["schemas"]?[OpenApiEmitter.ScopeSchema] as JsonObject ?? [];
        var leaves = DocumentReader.LeavesOf(schema);

        AppendLiterals(built, "Scope", leaves);
        AppendPlainClass(
            built,
            "ScopeResource",
            "A tenant, a subscription or a resource group, as the API renders it. ⚠ There is no provisioningState: a scope converges before the call returns.",
            leaves,
            EnumNaming.For("Scope", leaves),
            writable: false
        );

        foreach (var scope in scopes.Where(x => x.Creatable)) {
            var name = ScopeContent(scope);
            var body = DocumentReader.LeavesOf(scope.Body);

            AppendLiterals(built, name, body);
            AppendPlainClass(
                built,
                name,
                "The body of a PUT that creates a " + scope.DisplayName.ToLowerInvariant() + ".",
                body,
                EnumNaming.For(name, body),
                writable: true
            );
        }
    }

    /// <summary>
    ///     <c>ProvisioningState</c> once for the file, from the document's <c>Resource</c> component
    ///     — the read envelope every type shares (#85).
    /// </summary>
    static void AppendProvisioningState(StringBuilder built, JsonObject document) {
        if (document["components"]?["schemas"]?[OpenApiEmitter.ResourceEnvelopeSchema] is not JsonObject envelope) {
            return;
        }

        AppendLiterals(built, string.Empty, DocumentReader.LeavesOf(envelope));
    }

    static void AppendTypeModels(StringBuilder built, DocumentType type, string model) {
        var leaves = DocumentReader.LeavesOf(type.Body);
        var naming = EnumNaming.For(model, leaves);

        AppendLiterals(built, model, leaves);

        AppendObjectClass(
            built,
            string.Empty,
            model + "Data",
            model + "Data",
            type.DisplayName + ". " + (type.Summary.Length > 0 ? type.Summary + " " : string.Empty) + "The body a caller writes.",
            type.Body,
            string.Empty,
            naming
        );

        // ⚠ THE READ SHAPE IS THE ENVELOPE PLUS THE WRITE BODY, AND BOTH HALVES COME FROM THE
        // DOCUMENT — issue #85. Flat rather than inherited: a dataclass base with a defaulted member
        // would put `data`, which has no default, after it, and Python refuses that ordering.
        var envelope = DocumentReader.LeavesOf(type.Envelope);
        var served = DocumentReader.ReadRequiredOf(type.Envelope);
        var members = new List<PyMember> {
            new("", "data", model + "Data", true, false, model + "Data.from_wire(wire)", "The body, as the caller wrote it and the manager holds it.")
        };

        foreach (var leaf in envelope) {
            if (leaf.IsObject) {
                continue;
            }

            members.Add(Member(leaf with { Required = served.Contains(leaf.Name) }, EnumNaming.For(string.Empty, envelope), string.Empty));
        }

        AppendClassFrom(
            built,
            string.Empty,
            model + "Resource",
            "One " + type.DisplayName + ", as the API returns it: the Resource envelope, then the body, then tags.",
            members,
            writable: false
        );

        foreach (var action in type.Actions) {
            if (action.Request is { } request) {
                var name = model + SdkEmitter.Pascal(action.Name) + "Content";
                var requestLeaves = DocumentReader.LeavesOf(request);

                AppendLiterals(built, name, requestLeaves);
                AppendObjectClass(built, string.Empty, name, name, "The parameters of " + action.Name + ".", request, string.Empty, EnumNaming.For(name, requestLeaves));
            }

            if (action.Response is { } response) {
                var name = model + SdkEmitter.Pascal(action.Name) + "Result";
                var responseLeaves = DocumentReader.LeavesOf(response);

                AppendLiterals(built, name, responseLeaves);
                AppendObjectClass(
                    built,
                    string.Empty,
                    name,
                    name,
                    "What " + action.Name + " returns." + (action.Secret ? " ⚠ Secret material — never log or persist this." : string.Empty),
                    response,
                    string.Empty,
                    EnumNaming.For(name, responseLeaves)
                );
            }
        }
    }

    /// <summary>One <c>Literal</c> alias per closed set, before the class that names them.</summary>
    static void AppendLiterals(StringBuilder built, string model, ImmutableArray<SchemaLeaf> leaves) {
        var naming = EnumNaming.For(model, leaves);

        foreach (var leaf in leaves) {
            var values = DocumentReader.EnumOf(leaf.Schema);

            if (leaf.IsObject || values.IsEmpty) {
                continue;
            }

            built.Append("\n\n").Append(naming.NameOf(leaf)).Append(" = ");
            AppendLiteral(built, values);
            built.Append("\n\"\"\"The values ")
                .Append(Docstring(leaf.JsonPointer))
                .Append(
                    DocumentReader.Flag(leaf.Schema["readOnly"])
                        ? " carries. ⚠ Read-only: the server sets it, and a write that carries it is refused.\"\"\"\n"
                        : " accepts. ⚠ Closed: the write path refuses anything else.\"\"\"\n"
                );
        }
    }

    static void AppendLiteral(StringBuilder built, ImmutableArray<string> values) {
        if (values.IsEmpty) {
            built.Append("str");
            return;
        }

        built.Append("Literal[");

        for (var i = 0; i < values.Length; i++) {
            built.Append(i == 0 ? string.Empty : ", ").Append(Quote(values[i]));
        }

        built.Append(']');
    }

    /// <summary>One leaf, as a dataclass member and its two wire directions.</summary>
    /// <param name="WireName">The member name on the wire. Empty for a synthetic member such as <c>data</c>.</param>
    /// <param name="Name">The Python identifier.</param>
    /// <param name="Type">The annotation.</param>
    /// <param name="Required">Whether the member has no default.</param>
    /// <param name="ReadOnly">Whether <c>to_wire</c> leaves it out.</param>
    /// <param name="Read">The expression <c>from_wire</c> evaluates over <c>wire</c>.</param>
    /// <param name="Doc">A comment above the member, or empty.</param>
    readonly record struct PyMember(string WireName, string Name, string Type, bool Required, bool ReadOnly, string Read, string Doc);

    /// <summary>A scalar leaf as a member; a container is built by <see cref="AppendObjectClass" />.</summary>
    static PyMember Member(SchemaLeaf leaf, EnumNaming naming, string owner) {
        var name = Identifier(leaf.Name);
        var type = PyType(leaf, naming, owner);
        var required = leaf.Required;
        var read = required ? "wire[" + Quote(leaf.Name) + "]" : "wire.get(" + Quote(leaf.Name) + ")";

        return new(
            leaf.Name,
            name,
            type,
            required,
            DocumentReader.Flag(leaf.Schema["readOnly"]),
            read,
            DocumentReader.Text(leaf.Schema["description"])
        );
    }

    /// <summary>A class over scalar leaves only — the envelope shapes, which nest nothing.</summary>
    static void AppendPlainClass(
        StringBuilder built,
        string name,
        string doc,
        ImmutableArray<SchemaLeaf> leaves,
        EnumNaming naming,
        bool writable
    ) {
        var members = new List<PyMember>();

        foreach (var leaf in leaves) {
            if (!leaf.IsObject) {
                members.Add(Member(leaf, naming, name));
            }
        }

        AppendClassFrom(built, string.Empty, name, doc, members, writable);
    }

    /// <summary>
    ///     One object schema as a dataclass, its containers as nested dataclasses.
    /// </summary>
    /// <remarks>
    ///     ⚠ <b>Nested classes, for the reason issue #79 gave the .NET SDK them.</b> A flat class
    ///     has no correct wire name for a nested leaf: <c>/properties/mode</c> and
    ///     <c>/properties/persistence/mode</c> are two members named <c>mode</c> in two objects, and
    ///     a class holding both must rename one and then remember, in its serializer, which one
    ///     was renamed. A nested class per container keeps every leaf's own name at every depth.
    ///     <c>qualified</c> is the dotted name from the module — what an annotation writes.
    /// </remarks>
    static void AppendObjectClass(
        StringBuilder built,
        string indent,
        string name,
        string qualified,
        string doc,
        JsonObject schema,
        string pointer,
        EnumNaming naming
    ) {
        var members = new List<PyMember>();
        var nested = new List<(string Name, string Qualified, SchemaLeaf Leaf)>();
        var taken = new Dictionary<string, string>(StringComparer.Ordinal);

        if (schema["properties"] is JsonObject properties) {
            var required = schema["required"] is JsonArray names
                ? names.Select(DocumentReader.Text).ToHashSet(StringComparer.Ordinal)
                : [];

            foreach (var member in properties.ToList().OrderBy(x => x.Key, StringComparer.Ordinal)) {
                if (member.Value is not JsonObject child) {
                    continue;
                }

                var isObject = DocumentReader.TypeOf(child) == "object" && child["properties"] is JsonObject;
                var leaf = new SchemaLeaf(pointer + "/" + member.Key, member.Key, child, required.Contains(member.Key), isObject);
                var identifier = Identifier(member.Key);

                Claim(taken, identifier, leaf.JsonPointer, qualified);

                if (!isObject) {
                    members.Add(Member(leaf, naming, qualified));
                    continue;
                }

                var childClass = SdkEmitter.Pascal(member.Key);
                Claim(taken, childClass, leaf.JsonPointer + " (its class)", qualified);

                var childQualified = qualified + "." + childClass;
                nested.Add((childClass, childQualified, leaf));

                members.Add(
                    new(
                        member.Key,
                        identifier,
                        childQualified,
                        leaf.Required,
                        false,
                        leaf.Required
                            ? childQualified + ".from_wire(wire[" + Quote(member.Key) + "])"
                            : "_opt(wire, " + Quote(member.Key) + ", " + childQualified + ".from_wire)",
                        DocumentReader.Text(child["description"])
                    )
                );
            }
        }

        built.Append('\n').Append(indent.Length == 0 ? "\n" : string.Empty)
            .Append(indent).Append("@dataclass\n")
            .Append(indent).Append("class ").Append(name).Append(":\n")
            .Append(indent).Append("    \"\"\"").Append(Docstring(doc)).Append("\"\"\"\n");

        foreach (var (childName, childQualified, leaf) in nested) {
            AppendObjectClass(
                built,
                indent + "    ",
                childName,
                childQualified,
                DocumentReader.Text(leaf.Schema["description"]) is { Length: > 0 } text ? text : "The " + leaf.Name + " object.",
                leaf.Schema,
                leaf.JsonPointer,
                naming
            );
        }

        // ⚠ The qualified name in from_wire's return annotation, never the bare one: a method's
        // annotations are resolved from the module, not from the class bodies around it, so a
        // nested class naming itself would name nothing.
        AppendMembers(built, indent + "    ", qualified, members, writable: true, nestedContainers: nested.Select(x => x.Leaf.Name).ToHashSet(StringComparer.Ordinal));
    }

    static void AppendClassFrom(StringBuilder built, string indent, string name, string doc, List<PyMember> members, bool writable) {
        built.Append("\n\n")
            .Append(indent).Append("@dataclass\n")
            .Append(indent).Append("class ").Append(name).Append(":\n")
            .Append(indent).Append("    \"\"\"").Append(Docstring(doc)).Append("\"\"\"\n");

        AppendMembers(built, indent + "    ", name, members, writable, []);
    }

    /// <summary>
    ///     The members, then <c>from_wire</c>, then <c>to_wire</c>.
    /// </summary>
    /// <remarks>
    ///     ⚠ Required members first, then defaulted ones, each group sorted by name: a dataclass
    ///     refuses a member without a default after one with a default, so the document's ordinal
    ///     order cannot be kept as it is.
    /// </remarks>
    static void AppendMembers(
        StringBuilder built,
        string indent,
        string name,
        List<PyMember> members,
        bool writable,
        HashSet<string> nestedContainers
    ) {
        var ordered = members.Where(x => x.Required).OrderBy(x => x.Name, StringComparer.Ordinal)
            .Concat(members.Where(x => !x.Required).OrderBy(x => x.Name, StringComparer.Ordinal))
            .ToList();

        built.Append('\n');

        foreach (var member in ordered) {
            if (member.Doc.Length > 0) {
                built.Append(indent).Append("# ").Append(Comment(member.Doc)).Append('\n');
            }

            // ⚠ Optional is added here and not by the caller, so a nullable leaf that is also absent
            // reads Optional[str] once rather than Optional[Optional[str]].
            var annotation = member.Required || member.Type.StartsWith("Optional[", StringComparison.Ordinal)
                ? member.Type
                : "Optional[" + member.Type + "]";

            built.Append(indent).Append(member.Name).Append(": ").Append(annotation);

            if (!member.Required) {
                built.Append(" = None");
            }

            built.Append('\n');
        }

        if (ordered.Count == 0) {
            built.Append(indent).Append("# The document declares no member.\n");
        }

        built.Append('\n')
            .Append(indent).Append("@classmethod\n")
            .Append(indent).Append("def from_wire(cls, wire: Wire) -> ").Append(name).Append(":\n")
            .Append(indent).Append("    \"\"\"Reads one off the wire. Unknown members are ignored.\"\"\"\n")
            .Append(indent).Append("    return cls(\n");

        foreach (var member in ordered) {
            built.Append(indent).Append("        ").Append(member.Name).Append('=').Append(member.Read).Append(",\n");
        }

        built.Append(indent).Append("    )\n");

        if (!writable) {
            return;
        }

        built.Append('\n')
            .Append(indent).Append("def to_wire(self) -> Wire:\n")
            .Append(indent).Append("    \"\"\"Writes the members that are set. ⚠ A read-only member is never written: the write path refuses it.\"\"\"\n")
            .Append(indent).Append("    wire: Wire = {}\n");

        foreach (var member in ordered) {
            if (member.ReadOnly || member.WireName.Length == 0) {
                continue;
            }

            var value = nestedContainers.Contains(member.WireName)
                ? "self." + member.Name + ".to_wire()"
                : "self." + member.Name;

            if (member.Required) {
                built.Append(indent).Append("    wire[").Append(Quote(member.WireName)).Append("] = ").Append(value).Append('\n');
            } else {
                built.Append(indent).Append("    if self.").Append(member.Name).Append(" is not None:\n")
                    .Append(indent).Append("        wire[").Append(Quote(member.WireName)).Append("] = ").Append(value).Append('\n');
            }
        }

        built.Append(indent).Append("    return wire\n");
    }

    static void Claim(Dictionary<string, string> taken, string identifier, string pointer, string owner) {
        if (identifier is "from_wire" or "to_wire" or "wire") {
            throw new InvalidOperationException(
                $"'{pointer}' would be the member '{identifier}' on {owner}, which is the name of the "
                + "method that reads or writes it. Rename the property."
            );
        }

        if (taken.TryGetValue(identifier, out var other)) {
            throw new InvalidOperationException(
                $"'{pointer}' and '{other}' would both be '{identifier}' on {owner}. Two members with one "
                + "Python name cannot both be read, and the error would surface in a consumer's type "
                + "checker rather than here."
            );
        }

        taken[identifier] = pointer;
    }

    /// <summary>The annotation of one scalar leaf.</summary>
    static string PyType(SchemaLeaf leaf, EnumNaming naming, string owner) {
        var schema = leaf.Schema;
        var values = DocumentReader.EnumOf(schema);
        var nullable = DocumentReader.IsNullable(schema);

        var bare = !values.IsEmpty && naming.Model is not null && DocumentReader.TypeOf(schema) != "array"
            ? naming.NameOf(leaf)
            : DocumentReader.TypeOf(schema) switch {
                "array" => "List[" + Scalar(schema["items"] as JsonObject ?? [], naming, leaf) + "]",
                "object" => "Dict[str, str]",
                var scalar => Scalar(schema, naming, leaf, scalar)
            };

        return nullable ? "Optional[" + bare + "]" : bare;
    }

    static string Scalar(JsonObject schema, EnumNaming naming, SchemaLeaf leaf, string? declared = null) {
        if (!DocumentReader.EnumOf(schema).IsEmpty && naming.Model is not null && DocumentReader.TypeOf(leaf.Schema) == "array") {
            return naming.NameOf(leaf);
        }

        return (declared ?? DocumentReader.TypeOf(schema)) switch {
            "integer" => "int",
            "number" => "float",
            "boolean" => "bool",
            "string" => "str",
            _ => "Any"
        };
    }

    /// <summary>
    ///     How one model's <c>Literal</c> aliases are named — <see cref="TypeScriptEmitter" />'s
    ///     rule, for the same colliding pair: <c>mode</c> at two depths in the Cache provider.
    /// </summary>
    readonly record struct EnumNaming(string Model, ImmutableHashSet<string> Ambiguous) {
        public static EnumNaming For(string model, ImmutableArray<SchemaLeaf> leaves) {
            var counts = new Dictionary<string, int>(StringComparer.Ordinal);

            foreach (var leaf in leaves) {
                if (leaf.IsObject || DocumentReader.EnumOf(leaf.Schema).IsEmpty) {
                    continue;
                }

                counts[leaf.Name] = counts.GetValueOrDefault(leaf.Name) + 1;
            }

            return new(model, [.. counts.Where(x => x.Value > 1).Select(x => x.Key)]);
        }

        public string NameOf(SchemaLeaf leaf) =>
            Model + (Ambiguous.Contains(leaf.Name) ? NestedName(leaf.JsonPointer) : SdkEmitter.Pascal(leaf.Name));
    }

    static string NestedName(string jsonPointer) {
        var segments = jsonPointer.Split('/', StringSplitOptions.RemoveEmptyEntries);

        if (segments.Length > 1 && string.Equals(segments[0], "properties", StringComparison.Ordinal)) {
            segments = segments[1..];
        }

        return string.Concat(segments.Select(SdkEmitter.Pascal));
    }

